"""
Объяснение алгоритма:

1. Префиксные суммы (Prefix Sum)

    Создаем дополнительную матрицу prefix размером (m+1) x (n+1), где prefix[i+1][j+1] хранит сумму всех элементов в прямоугольнике от (0,0) до (i,j) включительно.

    Заполняем её за один проход по формуле:
    text

prefix[i+1][j+1] = prefix[i][j+1] + prefix[i+1][j] - prefix[i][j] + mat[i][j]

2. Вычисление суммы в прямоугольнике

    Для каждой ячейки (i, j) определяем границы окрестности:

        r1 = max(0, i-k) — верхняя граница (не выходим за пределы матрицы)

        r2 = min(m-1, i+k) — нижняя граница

        c1 = max(0, j-k) — левая граница

        c2 = min(n-1, j+k) — правая граница

    Сумма в прямоугольнике [r1..r2] x [c1..c2] вычисляется за O(1) по формуле:
    text

sum = prefix[r2+1][c2+1] - prefix[r1][c2+1] - prefix[r2+1][c1] + prefix[r1][c1]

3. Временная сложность

    Построение префиксных сумм: O(m * n)

    Вычисление ответа для каждой ячейки: O(m * n)

    Итого: O(m * n) — оптимальное решение

4. Пространственная сложность

    Дополнительная матрица префиксных сумм: O(m * n)

    Результирующая матрица: O(m * n)

    Итого: O(m * n)"""
