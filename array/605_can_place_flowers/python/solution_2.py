class Solution:
    def canPlaceFlowers(self, flowerbed: list[int], n: int) -> bool:
        """
        Проверяет, можно ли посадить n цветов в клумбу без нарушения правила
        "никаких соседних цветов".
        """

        # === ТРЮК: Добавляем нули по краям массива ===
        # Это элегантное решение проблемы краевых случаев!
        # Вместо того чтобы проверять (i == 0) или (i == len-1),
        # мы добавляем фиктивные пустые грядки в начало и конец.
        #
        # Пример: [1, 0, 0, 0, 1] превращается в [0, 1, 0, 0, 0, 1, 0]
        # Теперь для первого реального элемента (индекс 1) левый сосед —
        # фиктивный 0, и проверка работает автоматически.
        #
        # Важно: создаётся НОВЫЙ список, исходный flowerbed не меняется.
        flowerbed = [0] + flowerbed + [0]

        # === Проходим по всем реальным грядкам ===
        # range(1, len(flowerbed)-1) — пропускаем фиктивные нули на краях.
        # Для flowerbed из 5 элементов после добавления нулей длина = 7,
        # и мы идём по индексам 1, 2, 3, 4, 5 (реальные грядки).
        for i in range(1, len(flowerbed) - 1):
            # Проверяем три условия одновременно:
            # 1. Текущая грядка пуста
            # 2. Левая грядка пуста
            # 3. Правая грядка пуста
            # Благодаря фиктивным нулям по краям, не нужно проверять
            # выход за границы массива — это работает автоматически!
            if flowerbed[i] == 0 and flowerbed[i - 1] == 0 and flowerbed[i + 1] == 0:
                # Сажаем цветок — помечаем грядку как занятую
                flowerbed[i] = 1

                # Уменьшаем счётчик нужных цветов
                n -= 1
                # Ранний выход: если посадили все цветы
                if n == 0:
                    return True
        # Если n <= 0, значит мы посадили все нужные цветы (или даже больше)
        # Возвращаем True в этом случае, иначе False
        return n <= 0
