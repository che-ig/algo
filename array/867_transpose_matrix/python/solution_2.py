class Solution:
    def transpose(self, matrix: list[list[int]]) -> list[list[int]]:
        """
        Возвращает транспонированную матрицу.
        Строки исходной матрицы становятся столбцами результирующей,
        и наоборот: matrix[i][j] -> result[j][i].
        """
        # Получаем размеры исходной матрицы
        rows = len(matrix)  # количество строк (m)
        cols = len(matrix[0])  # количество столбцов (n)

        # Результирующий список, который будет содержать транспонированную матрицу.
        # Изначально пуст — будем добавлять строки по мере их формирования.
        ans = []

        # Внешний цикл идёт по столбцам исходной матрицы (0..cols-1).
        # Каждый столбец исходной матрицы становится строкой в результирующей.
        for r in range(cols):
            # Создаём новую пустую строку для результирующей матрицы.
            # Это будет r-я строка транспонированной матрицы.
            row = []

            # Внутренний цикл идёт по строкам исходной матрицы (0..rows-1).
            # Для каждой строки c берём элемент matrix[c][r] —
            # то есть элемент из строки c и столбца r исходной матрицы.
            for c in range(rows):
                # Добавляем элемент в текущую строку результата.
                # matrix[c][r] — это элемент на пересечении строки c и столбца r.
                # В транспонированной матрице он окажется на позиции (r, c).
                row.append(matrix[c][r])

            # ВАЖНО: эта строка должна быть на уровне ВНЕШНЕГО цикла (for r),
            # а не внутреннего (for c)!
            # Добавляем полностью сформированную строку в результат
            # только после того, как собрали все её элементы.
            ans.append(row)

        return ans
