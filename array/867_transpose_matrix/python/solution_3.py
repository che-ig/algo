class Solution:
    def transpose(self, matrix: list[list[int]]) -> list[list[int]]:
        """
        Транспонирует КВАДРАТНУЮ матрицу in-place.
        Меняет местами элементы matrix[r][c] и matrix[c][r]
        только для элементов выше главной диагонали.

        ВНИМАНИЕ: этот подход НЕ работает для прямоугольных матриц!
        """
        n = len(matrix)  # Для квадратной матрицы rows == cols == n

        # Проходим по всем строкам
        for r in range(n):
            # Внутренний цикл начинается с r+1, чтобы:
            # 1. Не менять элементы главной диагонали (r == c) — они остаются на месте
            # 2. Не делать двойной обмен (если бы начинали с 0, поменяли бы дважды)
            for c in range(r + 1, n):
                # Меняем местами симметричные элементы относительно главной диагонали
                # matrix[r][c] ↔ matrix[c][r]
                #
                # Пример для матрицы 3x3:
                # При r=0, c=1: меняем matrix[0][1] и matrix[1][0]
                # При r=0, c=2: меняем matrix[0][2] и matrix[2][0]
                # При r=1, c=2: меняем matrix[1][2] и matrix[2][1]
                matrix[r][c], matrix[c][r] = matrix[c][r], matrix[r][c]

        return matrix  # ВАЖНО: не забываем вернуть результат!
