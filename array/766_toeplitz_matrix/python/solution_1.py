class Solution:
    def isToeplitzMatrix(self, matrix: list[list[int]]) -> bool:
        """
        Проверяет, является ли матрица матрицей Теплица.
        Сравнивает каждый элемент с элементом на позиции (i+1, j+1).
        """
        m = len(matrix)
        n = len(matrix[0])

        # Проходим по всем элементам, кроме последнего столбца и последней строки.
        # Нам не нужно проверять элементы в последней строке и последнем столбце,
        # так как у них нет "нижнего правого" соседа.
        for i in range(m - 1):
            for j in range(n - 1):
                # Если текущий элемент не равен элементу по диагонали справа-внизу,
                # значит, диагональ содержит разные элементы.
                if matrix[i][j] != matrix[i + 1][j + 1]:
                    return False

        # Если все пары совпали, матрица является матрицей Теплица
        return True


