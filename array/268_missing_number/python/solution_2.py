class Solution:
    def missingNumber(self, nums: list[int]) -> int:
        """
        Возвращает пропущенное число используя множество.

        Создаём set из всех чисел массива, затем проверяем каждое число
        от 0 до n. Первое число, которого нет в set — и есть ответ.
        """
        # Создаём множество из элементов массива.
        # Это занимает O(N) времени и O(N) памяти.
        # Поиск в set работает за O(1) в среднем.
        num_set = set(nums)

        # n — это длина массива, и диапазон чисел [0, n]
        n = len(nums)

        # Проверяем каждое число от 0 до n включительно
        for i in range(n + 1):
            # Если число не найдено в множестве — это пропущенное число
            if i not in num_set:
                return i

        # Теоретически сюда мы не дойдём, так как по условию
        # всегда есть ровно одно пропущенное число
        return -1
