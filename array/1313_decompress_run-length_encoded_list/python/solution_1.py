class Solution:
    def decompressRLElist(self, nums: list[int]) -> list[int]:
        """
        Разжимает список, закодированный в формате RLE (Run-Length Encoding).

        Входной массив nums содержит пары (freq, val):
        - nums[0] = частота, nums[1] = значение
        - nums[2] = частота, nums[3] = значение
        - и так далее...

        Например, nums = [1, 2, 3, 4] означает:
        - 1 раз значение 2 → [2]
        - 3 раза значение 4 → [4, 4, 4]
        - Итог: [2, 4, 4, 4]
        """
        # Инициализируем пустой список для результата
        ans = []

        # Проходим по массиву с шагом 2, чтобы обрабатывать пары (freq, val).
        # range(0, len(nums), 2) генерирует индексы: 0, 2, 4, 6, ...
        # На каждой итерации:
        #   nums[i]   — это частота (сколько раз повторить значение)
        #   nums[i+1] — это само значение
        for i in range(0, len(nums), 2):
            # Создаём список из nums[i+1], повторённый nums[i] раз.
            # Оператор * для списков в Python повторяет элементы.
            # Например: [4] * 3 → [4, 4, 4]
            #
            # Затем добавляем этот список к ans через оператор +=,
            # который расширяет ans элементами нового списка (аналог extend).
            #
            # ВАЖНО: здесь используется += (extend), а не append,
            # потому что append добавил бы весь список как один вложенный элемент:
            #   ans.append([4, 4, 4]) → ans = [[4, 4, 4]]  ❌
            #   ans += [4, 4, 4]      → ans = [4, 4, 4]    ✓
            ans += [nums[i + 1]] * nums[i]

        # Возвращаем разжатый список
        return ans
