class Solution:
    def arrayPairSum(self, nums: list[int]) -> int:
        # Диапазон значений от -10000 до 10000.
        # Сдвигаем все числа на +10000, чтобы индексы были неотрицательными.
        offset = 10000
        counts = [0] * 20001

        # Считаем частоты каждого числа
        for num in nums:
            counts[num + offset] += 1

        total_sum = 0
        is_even_index = True  # Флаг: берём ли мы текущее число в сумму

        # Проходим по всем возможным значениям от минимального к максимальному
        for i in range(20001):
            while counts[i] > 0:
                # Если это "чётная" позиция в отсортированном порядке — добавляем к сумме
                if is_even_index:
                    total_sum += i - offset

                # Переключаем флаг и уменьшаем счётчик
                is_even_index = not is_even_index
                # В алгоритме сортировки подсчётом (Counting Sort) массив counts хранит количество раз, которое каждое число встречается в исходном массиве.
                # Когда мы проходим по массиву counts во внутреннем цикле while counts[i] > 0:, мы как бы "разворачиваем" сжатый массив частот обратно в обычный отсортированный массив. На каждом шаге этого цикла while мы обрабатываем ровно одну копию числа i.
                # Строка counts[i] -= 1 означает: "Мы только что взяли и обработали одну копию этого числа, поэтому уменьшаем количество оставшихся необработанных копий на 1".
                counts[i] -= 1

        return total_sum
