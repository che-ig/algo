# Время: O(log3 n)
# O(log3n) — число делится на 3 на каждом шаге. Для int32 это максимум 19 рекурсивных вызовов.
# Память: O(log3n)
# O(log3n) — глубина стека вызовов.
class Solution:
    def isPowerOfThree(self, n: int) -> bool:
        """
        Рекурсивная проверка: является ли n степенью тройки.

        Логика:
        - Все степени тройки положительны → n <= 0 возвращает False
        - 3^0 = 1 → n == 1 возвращает True (базовый случай успеха)
        - Если n не делится на 3, но не равно 1 → это не степень тройки
        - Иначе рекурсивно проверяем n // 3

        Args:
            n: Проверяемое целое число

        Returns:
            True, если n является степенью тройки, иначе False
        """
        # Базовый случай 1: степень тройки всегда строго положительна
        # Это также защищает от бесконечной рекурсии для n = 0
        if n <= 0:
            return False

        # Базовый случай 2: дошли до 1 = 3^0 → исходное число было степенью тройки
        if n == 1:
            return True

        # Если число не делится на 3 и при этом не равно 1,
        # значит в его разложении есть другой множитель → не степень тройки
        if n % 3 != 0:
            return False

        # Шаг рекурсии: проверяем число, уменьшенное в 3 раза
        return self.isPowerOfThree(n // 3)
