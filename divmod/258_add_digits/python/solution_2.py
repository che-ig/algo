class Solution:
    def addDigits(self, num: int) -> int:
        """
        Возвращает цифровой корень числа за O(1) времени.

        Формула цифрового корня:
        - Если num == 0, ответ 0
        - Если num > 0, ответ 1 + (num - 1) % 9

        Это эквивалентно:
        - num % 9, если num % 9 != 0
        - 9, если num % 9 == 0 и num > 0
        - 0, если num == 0
        """
        # Обработка edge case: если число 0, цифровой корень тоже 0
        if num == 0:
            return 0

        # Формула цифрового корня для положительных чисел.
        #
        # Почему это работает?
        # Любое число можно представить как: num = 9*q + r, где r = num % 9.
        # При сложении цифр числа мы фактически вычисляем его остаток от деления на 9
        # (это следует из того, что 10 ≡ 1 (mod 9), 100  1 (mod 9), и т.д.).
        #
        # Если num делится на 9 (r = 0), то цифровой корень равен 9 (не 0),
        # потому что мы продолжаем складывать цифры, пока не получим одну цифру.
        # Например: 18 → 1+8 = 9, 27 → 2+7 = 9, 99 → 9+9 = 18 → 1+8 = 9.
        #
        # Формула 1 + (num - 1) % 9 корректно обрабатывает оба случая:
        # - Если num = 9: 1 + (9-1) % 9 = 1 + 8 = 9 ✓
        # - Если num = 18: 1 + (18-1) % 9 = 1 + 17 % 9 = 1 + 8 = 9 ✓
        # - Если num = 38: 1 + (38-1) % 9 = 1 + 37 % 9 = 1 + 1 = 2 ✓
        return 1 + (num - 1) % 9
