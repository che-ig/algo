# time o(lon n)
# mev o(1)
class Solution:
    def addDigits(self, num: int) -> int:
        """
        Многократно складывает цифры числа, пока не получится одна цифра.
        Использует цикл для симуляции процесса.
        """
        # Пока число состоит из более чем одной цифры (то есть >= 10)
        while num >= 10:
            # digit_sum — сумма цифр текущего числа
            digit_sum = 0

            # Извлекаем все цифры числа и складываем их
            while num > 0:
                digit_sum += num % 10  # Добавляем последнюю цифру
                num //= 10  # Отбрасываем последнюю цифру

            # Заменяем num на сумму его цифр
            num = digit_sum

        # Когда цикл завершён, num — это одна цифра (0-9)
        return num
