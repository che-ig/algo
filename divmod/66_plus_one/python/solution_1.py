class Solution:
    def plusOne(self, digits: list[int]) -> list[int]:
        """
        Прибавляет 1 к числу, представленному массивом цифр.
        Идем справа налево, имитируя сложение в столбик.
        """
        n = len(digits)

        # Проходим по массиву с конца (от младшего разряда к старшему).
        # range(n - 1, -1, -1) генерирует индексы от последнего до 0.
        for i in range(n - 1, -1, -1):
            # Прибавляем 1 к текущей цифре
            digits[i] += 1

            # Если после прибавления цифра меньше 10, переноса нет.
            # Мы успешно закончили сложение, возвращаем результат.
            if digits[i] < 10:
                return digits

            # Если цифра стала равна 10, мы записываем 0,
            # а единицу "помним в уме" (переносим в следующий разряд).
            # На следующей итерации цикла мы прибавим эту единицу к digits[i-1].
            digits[i] = 0

        # Если цикл завершился, а мы так и не сделали return,
        # это значит, что перенос был из самого старшего разряда.
        # Например: [9, 9] -> [0, 0], и нам нужно добавить 1 в самое начало.
        return [1] + digits
