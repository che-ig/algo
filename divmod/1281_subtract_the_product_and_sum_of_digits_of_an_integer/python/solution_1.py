class Solution:
    def subtractProductAndSum(self, n: int) -> int:
        """
        Возвращает разность между произведением цифр числа n и их суммой.

        Использует математический подход: извлекаем цифры через % 10 и // 10.
        """
        # product — произведение цифр. Инициализируем 1 (нейтральный элемент для умножения).
        product = 1

        # digit_sum — сумма цифр. Инициализируем 0 (нейтральный элемент для сложения).
        digit_sum = 0

        # Извлекаем цифры числа по одной, начиная с последней.
        # Цикл продолжается, пока n > 0 (то есть пока есть цифры для обработки).
        while n > 0:
            # Извлекаем последнюю цифру числа.
            # Например, для n = 234: 234 % 10 = 4
            digit = n % 10

            # Обновляем произведение и сумму
            product *= digit
            digit_sum += digit

            # Отбрасываем последнюю цифру.
            # Например, для n = 234: 234 // 10 = 23
            n //= 10

        # Возвращаем разность произведения и суммы
        return product - digit_sum
