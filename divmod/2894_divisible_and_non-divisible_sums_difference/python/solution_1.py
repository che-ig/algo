class Solution:
    def differenceOfSums(self, n: int, m: int) -> int:
        """
        Прямое решение через цикл.
        Считаем num1 и num2, проходя по всем числам от 1 до n.
        """
        num1 = 0  # Сумма чисел, НЕ кратных m
        num2 = 0  # Сумма чисел, кратных m

        # Проходим по всем числам от 1 до n включительно
        for i in range(1, n + 1):
            if i % m == 0:
                # Если число делится на m без остатка, добавляем к num2
                num2 += i
            else:
                # Иначе добавляем к num1
                num1 += i

        # Возвращаем разность
        return num1 - num2
