class Solution:
    def differenceOfSums(self, n: int, m: int) -> int:
        """
        Возвращает разность num1 - num2, где:
        num1 — сумма чисел от 1 до n, НЕ кратных m
        num2 — сумма чисел от 1 до n, кратных m

        Использует математическую формулу для решения за O(1).
        """
        # 1. Считаем общую сумму всех чисел от 1 до n.
        # Формула суммы арифметической прогрессии: n * (n + 1) / 2
        total_sum = n * (n + 1) // 2

        # 2. Находим количество чисел, кратных m, в диапазоне [1, n].
        # Это целая часть от деления n на m.
        # Например, для n=10, m=3: k = 10 // 3 = 3 (числа 3, 6, 9)
        k = n // m

        # 3. Считаем сумму чисел, кратных m (num2).
        # Эти числа: m*1, m*2, ..., m*k.
        # Выносим m за скобки: m * (1 + 2 + ... + k) = m * k * (k + 1) / 2
        num2 = m * k * (k + 1) // 2

        # 4. Вычисляем итоговый ответ.
        # num1 = total_sum - num2
        # Ответ = num1 - num2 = (total_sum - num2) - num2 = total_sum - 2 * num2
        return total_sum - 2 * num2
