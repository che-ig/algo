class Solution:
    def fizzBuzz(self, n: int) -> list[str]:
        """
        Альтернативное решение через конкатенацию строк.
        Более гибкое: легко добавлять новые правила (например, для 7).
        """
        answer = []

        for i in range(1, n + 1):
            # Начинаем с пустой строки для текущего числа
            res = ""

            # Если делится на 3, добавляем "Fizz"
            if i % 3 == 0:
                res += "Fizz"

            # Если делится на 5, добавляем "Buzz"
            # (если уже добавили "Fizz", получится "FizzBuzz")
            if i % 5 == 0:
                res += "Buzz"

            # Если строка всё ещё пустая, значит число не делится ни на 3, ни на 5.
            # В этом случае записываем само число.
            if not res:
                res = str(i)

            answer.append(res)

        return answer
