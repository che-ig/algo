# Сложность:
#     Время: O(2^n * n) на построение + хэширование кортежей.
#     Память: O(2^n * n) под set и результат.
# Для n ≤ 10 (2^10 = 1024) это мгновенно, но формально хуже, чем backtracking.


class Solution:
    def subsetsWithDup(self, nums: list[int]) -> list[list[int]]:
        """
        Генерация всех уникальных подмножеств через битовые маски.

        Стратегия:
        1. Сортируем массив
        2. Генерируем все 2^n подмножеств через битовые маски
        3. Используем set для удаления дубликатов

        Args:
            nums: Массив целых чисел (может содержать дубликаты)

        Returns:
            Список всех уникальных подмножеств
        """
        # Сортируем, чтобы дубликаты генерировали одинаковые кортежи
        nums.sort()

        n = len(nums)
        unique_subsets: set[tuple[int, ...]] = set()

        # Перебираем все 2^n подмножеств
        for mask in range(1 << n):  # 1 << n = 2^n
            subset: list[int] = []

            # Проверяем каждый бит маски
            for i in range(n):
                if mask & (1 << i):  # Если i-й бит равен 1
                    subset.append(nums[i])

            # Преобразуем в кортеж для добавления в set
            # set автоматически удалит дубликаты
            unique_subsets.add(tuple(subset))

        # Преобразуем обратно в список списков
        return [list(subset) for subset in unique_subsets]
