from collections import defaultdict


class Solution:
    def beautifulSubsets(self, nums: list[int], k: int) -> int:
        # Словарь для отслеживания частоты элементов в текущем подмножестве
        # Используем defaultdict для удобного получения 0, если элемента нет
        counts = defaultdict(int)

        def dfs(index: int) -> int:
            # Базовый случай: мы рассмотрели все элементы массива
            # Возвращаем 1, чтобы посчитать это валидное подмножество (включая пустое)
            if index == len(nums):
                return 1

            # Вариант 1: Исключаем текущий элемент nums[index]
            # Просто переходим к следующему элементу
            total_subsets = dfs(index + 1)

            # Вариант 2: Пытаемся включить текущий элемент nums[index]
            num = nums[index]

            # Проверяем, не нарушит ли добавление этого числа условие "красоты"
            # Если ни (num - k), ни (num + k) еще нет в нашем подмножестве
            if counts[num - k] == 0 and counts[num + k] == 0:
                # Добавляем число в подмножество
                counts[num] += 1

                # Рекурсивно считаем варианты для следующих элементов
                total_subsets += dfs(index + 1)

                # Backtrack (откат): удаляем число из подмножества,
                # чтобы исследовать другие ветки рекурсии
                counts[num] -= 1

            return total_subsets

        # Запускаем рекурсию с 0-го индекса
        # Вычитаем 1 в конце, чтобы исключить пустое подмножество,
        # так как по условию нужны только непустые подмножества
        return dfs(0) - 1
