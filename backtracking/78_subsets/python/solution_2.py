class Solution:
    def subsets(self, nums: list[int]) -> list[list[int]]:
        """
        Итеративная генерация всех подмножеств.

        Идея:
        - Начинаем с [[]]
        - Для каждого числа nums[i] добавляем его ко всем существующим подмножествам

        Пример для [1, 2, 3]:
        - Старт: [[]]
        - После 1: [[], [1]]
        - После 2: [[], [1], [2], [1, 2]]
        - После 3: [[], [1], [2], [1, 2], [3], [1, 3], [2, 3], [1, 2, 3]]
        """
        result: list[list[int]] = [[]]

        for num in nums:
            # Для каждого существующего подмножества создаём новое, добавляя num
            result += [subset + [num] for subset in result]

        return result
