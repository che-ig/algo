# Алгоритм Манакера — это элегантный алгоритм для нахождения самой длинной палиндромной подстроки за линейное время O(N). Он считается одним из самых красивых алгоритмов в теории строк, но сложен для понимания.
class Solution:
    def longestPalindrome(self, s: str) -> str:
        """
        Находит самую длинную палиндромную подстроку за O(N)
        с использованием алгоритма Манакера.
        """
        if not s:
            return ""

        # Шаг 1: Преобразуем строку
        # Вставляем '#' между символами и добавляем стражи '^' и '$'
        # "aba" -> "^#a#b#a#$"
        T = "^#" + "#".join(s) + "#$"
        n = len(T)

        # P[i] — радиус палиндрома с центром в позиции i
        P = [0] * n

        # C — центр самого правого известного палиндрома
        # R — правая граница самого правого известного палиндрома
        C = 0
        R = 0

        # Шаг 2: Заполняем массив P
        for i in range(1, n - 1):  # Пропускаем стражи '^' и '$'
            # Находим зеркальную позицию i' относительно центра C
            # i' = 2*C - i (симметрия относительно C)
            i_mirror = 2 * C - i

            # Если i внутри правого палиндрома (i < R),
            # используем симметрию для инициализации P[i]
            if R > i:
                # Берём минимум из P[i'] и расстояния до правой границы
                # Это гарантирует, что мы не выйдем за пределы известного палиндрома
                P[i] = min(R - i, P[i_mirror])
            else:
                # Если i >= R, начинаем с нуля
                P[i] = 0

            # Шаг 3: Пытаемся расширить палиндром с центром в i
            # Сравниваем символы слева и справа от i
            while T[i + 1 + P[i]] == T[i - 1 - P[i]]:
                P[i] += 1

            # Шаг 4: Если палиндром с центром в i выходит за правую границу R,
            # обновляем C и R
            if i + P[i] > R:
                C = i
                R = i + P[i]

        # Шаг 5: Находим максимальный радиус и его центр
        max_len = 0
        center_index = 0
        for i in range(1, n - 1):
            if P[i] > max_len:
                max_len = P[i]
                center_index = i

        # Шаг 6: Извлекаем исходный палиндром
        # В преобразованной строке центр в center_index, радиус max_len
        # Начало в исходной строке: (center_index - max_len) // 2
        start = (center_index - max_len) // 2
        return s[start : start + max_len]
