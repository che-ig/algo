class Solution:
    def longestPalindrome(self, s: str) -> str:
        """
        Возвращает самую длинную палиндромную подстроку.

        Используем подход "расширение от центра":
        для каждой позиции проверяем два возможных центра палиндрома
        (в символе и между символами) и расширяемся в обе стороны.
        """
        if not s or len(s) < 1:
            return ""

        # start и end — индексы начала и конца самой длинной найденной подстроки
        start = 0
        end = 0

        # Проходим по всем возможным центрам палиндрома
        for i in range(len(s)):
            # Проверяем палиндром нечётной длины (центр в символе i)
            # Например: "aba" — центр в 'b'
            len1 = self._expand_around_center(s, i, i)

            # Проверяем палиндром чётной длины (центр между символами i и i+1)
            # Например: "abba" — центр между 'b' и 'b'
            len2 = self._expand_around_center(s, i, i + 1)

            # Берём максимальную длину из двух вариантов
            max_len = max(len1, len2)

            # Если нашли палиндром длиннее текущего рекорда — обновляем границы
            if max_len > end - start:
                # Вычисляем новые границы:
                # Если длина нечётная (например, 5), центр в i,
                # то начало = i - 2, конец = i + 2
                # Если длина чётная (например, 4), центр между i и i+1,
                # то начало = i - 1, конец = i + 2
                # Универсальная формула: start = i - (max_len - 1) // 2
                start = i - (max_len - 1) // 2
                end = i + max_len // 2

        # Возвращаем подстроку от start до end включительно
        return s[start : end + 1]

    def _expand_around_center(self, s: str, left: int, right: int) -> int:
        """
        Расширяется от центра (left, right) в обе стороны,
        пока символы совпадают.

        Возвращает длину найденного палиндрома.
        """
        # Пока указатели в пределах строки и символы совпадают — расширяемся
        while left >= 0 and right < len(s) and s[left] == s[right]:
            left -= 1
            right += 1

        # После выхода из цикла left и right указывают на символы,
        # которые не совпадают (или вышли за границы).
        # Длина палиндрома = right - left - 1
        # Например: если left = 1, right = 5, палиндром был s[2..4], длина = 3
        return right - left - 1


def run_tests():
    solution = Solution()

    test_cases = [
        # Стандартные примеры
        ("babad", "bab", "Стандартный пример 1 (нечётный палиндром)"),
        ("cbbd", "bb", "Стандартный пример 2 (чётный палиндром)"),
        # Граничные случаи
        ("a", "a", "Один символ"),
        ("aa", "aa", "Два одинаковых символа"),
        ("ab", "a", "Два разных символа (любой из них)"),
        # Длинные палиндромы
        ("abcba", "abcba", "Вся строка — палиндром"),
        ("abacdfgdcaba", "aba", "Несколько палиндромов одинаковой длины"),
        ("racecar", "racecar", "Длинный нечётный палиндром"),
        # Чётные палиндромы
        ("abba", "abba", "Чётный палиндром"),
        ("abbac", "abba", "Чётный палиндром в начале"),
        ("cabbac", "abba", "Чётный палиндром в середине"),
        # Все одинаковые символы
        ("aaaa", "aaaa", "Все символы одинаковые"),
        ("aaaaa", "aaaaa", "Все символы одинаковые (нечётное количество)"),
    ]

    print("=" * 70)
    print("ТЕСТИРОВАНИЕ LONGEST PALINDROMIC SUBSTRING")
    print("=" * 70)

    passed = 0
    for s, expected, description in test_cases:
        result = solution.longestPalindrome(s)
        # Для "babad" допустимы оба ответа: "bab" и "aba"
        if result == expected or (s == "babad" and result in ["bab", "aba"]):
            print(f"✅ {description}: s='{s}' -> '{result}'")
            passed += 1
        else:
            print(f"❌ {description}: s='{s}'")
            print(f"   Ожидалось: '{expected}'")
            print(f"   Получено:  '{result}'")

    print("=" * 70)
    print(f"Результат: {passed}/{len(test_cases)} тестов пройдено")


run_tests()
