class Solution:
    def findTheDistanceValue(self, arr1: list[int], arr2: list[int], d: int) -> int:
        """
        Альтернативный подход: для каждого элемента из arr1
        находим позицию его вставки в отсортированный arr2
        с помощью бинарного поиска (без модуля bisect).

        Позиция вставки делит массив на две части:
          - слева элементы < x
          - справа элементы >= x
        Ближайшие соседи — это граница этого разделения.
        """

        # Сортируем arr2 один раз, чтобы потом для каждого элемента
        # из arr1 выполнять бинарный поиск за O(log m).
        arr2.sort()
        m = len(arr2)  # длина отсортированного arr2

        count = 0  # Счётчик подходящих элементов

        # Проходим по каждому элементу в arr1 (порядок не важен)
        for x in arr1:
            # --- Шаг 1: бинарный поиск позиции вставки ---
            # Ищем наименьший индекс pos такой, что arr2[pos] >= x.
            # Это эквивалентно тому, что делает bisect.bisect_left().
            #
            # Инварианты бинарного поиска:
            #   - Все элементы в [0, left)  < x
            #   - Все элементы в [right, m) >= x
            #   - left и right сходятся к позиции вставки
            #
            # Используем полуинтервал [left, right),
            # поэтому условие цикла: left < right

            left = 0  # левая граница поиска (включительно)
            right = m  # правая граница поиска (НЕ включительно)

            while left < right:
                # Вычисляем середину.
                # Используем (left + right) // 2, так как в Python
                # нет переполнения целых чисел.
                mid = (left + right) // 2

                if arr2[mid] < x:
                    # Элемент в середине меньше искомого.
                    # Значит позиция вставки правее середины.
                    # Отбрасываем левую половину ВКЛЮЧАЯ mid.
                    left = mid + 1
                else:
                    # arr2[mid] >= x.
                    # Это потенциальная позиция вставки,
                    # но может быть такая же или раньше.
                    # Отбрасываем правую половину, но mid оставляем.
                    right = mid

            # После цикла left == right == pos
            # pos — индекс первого элемента в arr2, который >= x
            #
            # Пример:
            #   arr2 = [1, 3, 7, 9], x = 5
            #   pos = 2 (arr2[2] = 7 — первый элемент >= 5)
            #
            #   arr2 = [1, 3, 5, 7], x = 5
            #   pos = 2 (arr2[2] = 5 — первый элемент >= 5)

            pos = left

            # --- Шаг 2: проверяем двух ближайших соседей ---
            # Ближайшие к x элементы в отсортированном массиве:
            #   1) Слева:  arr2[pos - 1]  (последний элемент < x)
            #   2) Справа: arr2[pos]      (первый элемент >= x)
            #
            # Аналогия: представьте, что вы вставили x в массив.
            # Его ближайшие соседи — это элемент слева и справа
            # от места вставки.

            valid = True  # Флаг: подходит ли элемент

            # Проверяем соседа СЛЕВА
            # Условие: pos > 0, т.е. слева есть хотя бы один элемент.
            # Если pos == 0, значит x меньше всех элементов в arr2,
            # и соседа слева не существует.
            if pos > 0:
                # Расстояние от x до ближайшего элемента слева
                distance_left = abs(arr2[pos - 1] - x)
                if distance_left <= d:
                    # Слишком близко — элемент НЕ подходит
                    valid = False

            # Проверяем соседа СПРАВА
            # Условие: pos < m, т.е. справа есть хотя бы один элемент.
            # Если pos == m, значит x больше всех элементов в arr2,
            # и соседа справа не существует.
            if pos < m:
                # Расстояние от x до ближайшего элемента справа
                distance_right = abs(arr2[pos] - x)
                if distance_right <= d:
                    # Слишком близко — элемент НЕ подходит
                    valid = False

            # --- Шаг 3: подсчёт результата ---
            # Если ни один из соседей не оказался на расстоянии <= d,
            # значит ВСЕ элементы в arr2 находятся дальше, чем d.
            # (Потому что все остальные элементы ещё дальше, чем соседи.)
            if valid:
                count += 1

        return count


# --- Проверка ---
if __name__ == "__main__":
    sol = Solution()

    # Пример 1:
    # arr2 после сортировки: [1, 8, 9, 10]
    # Для x=4: pos=1, слева 1 (дист.3), справа 8 (дист.4) → ✅
    # Для x=5: pos=1, слева 1 (дист.4), справа 8 (дист.3) → ✅
    # Для x=8: pos=1, слева 1 (дист.7), справа 8 (дист.0) → ❌
    # Ответ: 2
    print(sol.findTheDistanceValue([4, 5, 8], [10, 9, 1, 8], 2))

    # Пример 2: Ответ: 2
    print(sol.findTheDistanceValue([1, 4, 2, 3], [-4, -3, 6, 10, 20, 30], 3))

    # Пример 3: Ответ: 1
    print(sol.findTheDistanceValue([2, 1, 100, 3], [-5, -2, 10, -3, 7], 6))
