class Solution:
    def firstPalindrome(self, words: list[str]) -> str:
        """
        Возвращает первое палиндромное слово из массива.
        Если палиндромов нет, возвращает пустую строку.
        """
        # Проходим по каждому слову в массиве
        for word in words:
            # Проверяем, является ли слово палиндромом.
            # word[::-1] — это разворот строки (срез с шагом -1).
            # Если строка равна своему развороту — это палиндром.
            if word == word[::-1]:
                return word

        # Если ни одно слово не оказалось палиндромом — возвращаем ""
        return ""
