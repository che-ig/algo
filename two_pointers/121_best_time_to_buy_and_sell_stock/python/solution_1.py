class Solution:
    def maxProfit(self, prices):
        # left — указатель на день покупки (начинаем с первого дня)
        left = 0

        # right — указатель на день продажи (начинаем со второго дня)
        # Мы всегда продаём ПОСЛЕ покупки, поэтому right > left
        right = 1

        # Максимальная прибыль, которую мы можем получить
        # Инициализируем нулём (если прибыль невозможна, вернём 0)
        max_profit = 0

        # Проходим по массиву, пока right не достигнет конца
        while right < len(prices):
            # Вычисляем текущую прибыль, если бы мы купили в день left
            # и продали в день right
            current_profit = prices[right] - prices[left]

            if prices[left] < prices[right]:
                # Если цена продажи больше цены покупки,
                # значит эта сделка прибыльная
                # Обновляем максимальную прибыль, если текущая больше
                max_profit = max(current_profit, max_profit)
            else:
                # Если цена продажи <= цены покупки,
                # значит день right более выгоден для покупки, чем день left
                # (цена ниже или равна)
                # Перемещаем указатель покупки на этот день
                left = right

            # Всегда двигаем указатель продажи вперёд
            right += 1

        # Возвращаем максимальную найденную прибыль
        return max_profit
