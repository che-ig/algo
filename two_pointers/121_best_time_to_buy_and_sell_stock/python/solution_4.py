class Solution:
    def maxProfit(self, prices: list[int]) -> int:
        """
        Возвращает максимальную прибыль от одной покупки и одной продажи акций.

        Алгоритм: идём по массиву цен слева направо, поддерживая:
        1. min_price — минимальную цену, которую мы видели до текущего дня
           (лучшее время для покупки)
        2. ans — максимальную прибыль, которую мы могли бы получить,
           продав в один из предыдущих дней

        На каждом шаге:
        - Обновляем минимум цены (возможно, сегодня лучшая цена для покупки)
        - Вычисляем прибыль, если бы мы продали сегодня (price - min_price)
        - Обновляем максимум прибыли, если продажа сегодня выгоднее
        """

        # ans — максимальная прибыль, которую мы можем получить.
        # Инициализируем 0, так как по условию "если прибыли нет — возвращаем 0".
        # Это также гарантирует, что мы не вернём отрицательное значение
        # (например, если цены только падают).
        ans = 0

        # min_price — минимальная цена акции, которую мы видели на данный момент.
        # Инициализируем бесконечностью (float('inf')), чтобы любой реальный
        # элемент массива оказался меньше и обновил минимум на первой итерации.
        #
        # Альтернатива: можно инициализировать prices[0], но тогда нужно
        # начинать цикл со второго элемента (range(1, len(prices))).
        # Использование float('inf') позволяет начать цикл с первого элемента,
        # что делает код чуть короче и элегантнее.
        min_price = float("inf")

        # Проходим по всем ценам акций (по всем дням)
        for price in prices:
            # Шаг 1: Обновляем минимальную цену.
            # Если текущая цена меньше всех предыдущих, запоминаем её.
            # Это означает, что для всех будущих дней продажи лучшая цена
            # покупки — это текущий день.
            #
            # Пример: если min_price = 5, а price = 3, то min_price станет 3.
            # Теперь для любого будущего дня продажи мы будем считать прибыль
            # от покупки по цене 3, а не 5.
            min_price = min(min_price, price)

            # Шаг 2: Вычисляем и обновляем максимальную прибыль.
            # Если бы мы купили по минимальной цене (min_price) и продали
            # сегодня по цене price, наша прибыль составила бы (price - min_price).
            # Сравниваем это с текущим максимумом и обновляем, если выгодно.
            #
            # Пример: если ans = 4, price = 6, min_price = 1,
            # то profit = 6 - 1 = 5 > 4, и ans станет 5.
            ans = max(ans, price - min_price)

        # Возвращаем максимальную прибыль.
        # Если цены только падали, ans останется 0 (мы не совершаем сделку).
        return ans
