class Solution:
    def removeDuplicates(self, nums: list[int]) -> int:
        # По ограничениям задачи массив содержит минимум 1 элемент.
        # Если бы массив мог быть пустым, мы бы добавили проверку: if not nums: return 0

        # Указатель i показывает, сколько уникальных элементов мы уже нашли,
        # и одновременно является индексом для записи следующего уникального элемента.
        # Первый элемент nums[0] уже считается уникальным, поэтому начинаем с 1.
        i = 1

        # Указатель j пробегает по массиву, начиная со второго элемента (индекс 1)
        for j in range(1, len(nums)):
            # Так как массив отсортирован, нам достаточно сравнить текущий элемент
            # с предыдущим (nums[j - 1]). Если они не равны, значит мы нашли новый
            # уникальный элемент.
            if nums[j] != nums[j - 1]:
                # Записываем найденный уникальный элемент на позицию i
                nums[i] = nums[j]
                # Сдвигаем указатель записи вправо
                i += 1

        # Возвращаем количество уникальных элементов
        return i


# --- Проверка на примерах ---
if __name__ == "__main__":
    sol = Solution()

    nums1 = [1, 1, 2]
    k1 = sol.removeDuplicates(nums1)
    print(f"k = {k1}, nums = {nums1[:k1]}")
    # Ожидается: k = 2, nums = [1, 2]

    nums2 = [0, 0, 1, 1, 1, 2, 2, 3, 3, 4]
    k2 = sol.removeDuplicates(nums2)
    print(f"k = {k2}, nums = {nums2[:k2]}")
    # Ожидается: k = 5, nums = [0, 1, 2, 3, 4]
