class Solution:
    def largestSumAfterKNegations(self, nums: list[int], k: int) -> int:
        # Шаг 1: Сортируем массив, чтобы отрицательные числа (самые маленькие) оказались в начале
        nums.sort()

        # Шаг 2: Переворачиваем все отрицательные числа, пока у нас есть операции k
        for i in range(len(nums)):
            if nums[i] < 0 and k > 0:
                nums[i] = -nums[i]  # Делаем число положительным
                k -= 1
            else:
                # Как только встретили неотрицательное число или k закончилось, прерываем
                break

        # Шаг 3: Обрабатываем оставшиеся операции k
        # Если k нечетное, нам ПРИДЕТСЯ перевернуть наименьший элемент массива ровно 1 раз
        # (если k четное, мы можем перевернуть его четное число раз, и он останется положительным, сумма не изменится)
        if k % 2 == 1:
            min_val = min(nums)
            # Мы уже посчитали min_val как положительное число в sum(nums).
            # Чтобы сделать его отрицательным, нужно вычесть его из общей суммы ДВАЖДЫ.
            return sum(nums) - 2 * min_val

        # Если k == 0 или k четное, просто возвращаем сумму текущего массива
        return sum(nums)
