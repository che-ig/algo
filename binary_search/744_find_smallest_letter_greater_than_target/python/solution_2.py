class Solution:
    def nextGreatestLetter(self, letters: list[str], target: str) -> str:
        # Получаем количество букв в массиве
        N = len(letters)

        # Инициализируем левую границу поиска (начало массива)
        lo = 0

        # Инициализируем правую границу поиска (конец массива)
        hi = N - 1

        # Переменная для хранения ответа, -1 означает что буква не найдена
        ans = -1

        # Бинарный поиск пока границы не пересекутся
        while lo <= hi:
            # Находим средний индекс (защита от переполнения)
            mi = lo + (hi - lo) // 2

            if letters[mi] < target:
                # Если буква в середине меньше target, ищем в правой половине
                lo = mi + 1
            elif letters[mi] > target:
                # Если буква в середине больше target, запоминаем позицию
                # и продолжаем поиск влево (ищем наименьшую большую букву)
                ans = mi
                hi = mi - 1
            else:
                # Если буква равна target, продолжаем поиск вправо
                # (нам нужна буква строго больше target)
                lo = mi + 1

        # Если ans == -1, значит все буквы <= target,
        # возвращаем первую букву (циклический переход)
        if ans == -1:
            return letters[0]

        # Возвращаем найденную наименьшую букву, большую чем target
        return letters[ans]
