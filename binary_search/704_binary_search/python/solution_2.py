class Solution:
    def search(self, nums: list[int], target: int) -> int:
        """
        Ищет target в отсортированном массиве nums за O(log n).
        Возвращает индекс target или -1, если его нет.
        """
        # Указатели на левую и правую границы текущего поискового пространства
        left = 0
        right = len(nums) - 1

        # Цикл продолжается, пока поисковое пространство не схлопнется.
        # ВАЖНО: используем <=, чтобы проверить случай, когда left == right
        # (остался один элемент, и он может быть искомым).
        while left <= right:
            # Вычисляем средний индекс.
            # Формула left + (right - left) // 2 предотвращает переполнение
            # целочисленного типа в языках вроде C++ или Java.
            # В Python переполнения нет, но использование этой формулы
            # показывает interviewer'у вашу техническую грамотность.
            mid = left + (right - left) // 2

            # Сравниваем средний элемент с целевым
            if nums[mid] == target:
                return mid  # Нашли! Возвращаем индекс

            elif nums[mid] < target:
                # Если средний элемент меньше target, значит target
                # может находиться только в правой половине.
                # Сдвигаем левую границу вправо за mid.
                left = mid + 1

            else:
                # Если средний элемент больше target, значит target
                # может находиться только в левой половине.
                # Сдвигаем правую границу влево за mid.
                right = mid - 1

        # Если цикл завершился, а мы ничего не вернули,
        # значит элемента в массиве нет.
        return -1
