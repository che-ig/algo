class Solution:
    def maxLength(self, nums: list[int], k: int) -> int:
        # Вспомогательная функция для проверки, можно ли получить
        # как минимум k частей длиной 'length' из имеющихся лент
        def IsGood(length):
            # Счётчик общего количества частей, которые можно получить
            total = 0

            # Проходим по каждой ленте
            for num in nums:
                # Целочисленное деление: сколько частей длиной 'length'
                # поместится в ленту длиной 'num'
                # Например: лента 9, длина части 4 → 9 // 4 = 2 части
                total += num // length

            # Возвращаем True, если получили как минимум k частей
            return total >= k

        # Переменная для хранения ответа (максимальной найденной длины)
        # Инициализируем 0 (случай, когда невозможно получить k частей)
        ans = 0

        # Левая граница бинарного поиска (минимальная возможная длина части)
        lo = 1

        # Правая граница бинарного поиска (максимально возможная длина)
        # 10**9+1 — достаточно большое число, покрывающее все возможные значения
        # (по ограничениям задачи ribbons[i] <= 10^5, но берём с запасом)
        hi = 10**9 + 1
        # hi = max(nums)
        # Бинарный поиск максимального значения, для которого IsGood = True
        while lo <= hi:
            # Находим середину текущего диапазона (формула защищает от переполнения)
            mi = lo + (hi - lo) // 2

            if IsGood(mi):
                # Если можно получить k частей длиной mi:
                # 1. Запоминаем mi как потенциальный ответ
                ans = mi
                # 2. Пробуем увеличить длину (ищем максимум), сдвигаем левую границу
                lo = mi + 1
            else:
                # Если нельзя получить k частей длиной mi:
                # Длина слишком большая, нужно уменьшить
                # Сдвигаем правую границу влево
                hi = mi - 1

        # Возвращаем максимальную найденную длину
        # (или 0, если ни одна длина не подошла)
        return ans
