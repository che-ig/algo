class Solution:
    def isPerfectSquare(self, num: int) -> bool:
        """
        Проверяет, является ли num полным квадратом.
        Использует бинарный поиск с красно-синим инвариантом.
        """
        # Особый случай: 1 — полный квадрат (1 * 1 = 1)
        # Это нужно, чтобы избежать проблем с диапазоном поиска
        if num == 1:
            return True

        # Ищем первое x, для которого x * x >= num.
        # good(x) = (x * x >= num)
        # Массив условий: [False, False, ..., True, True]
        # Ищем первый True.

        l = 1  # Гарантированно False (1 * 1 = 1 < num для num > 1)
        r = num  # Гарантированно True (num * num >= num для num >= 1)

        while r - l > 1:
            m = (l + r) // 2

            # Проверяем условие: m * m >= num
            # ВАЖНО: в C++/Java m * m может вызвать переполнение.
            # Безопасная альтернатива: m >= num / m (целочисленное деление)
            if m * m >= num:
                r = m  # m подошел (Синий), он кандидат на первый True
            else:
                l = m  # m не подошел (Красный), отбрасываем его

        # По инварианту, r — это первое число, где r * r >= num.
        # Проверяем, является ли оно точным квадратом.
        return r * r == num
