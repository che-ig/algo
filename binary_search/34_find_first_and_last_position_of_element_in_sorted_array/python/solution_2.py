class Solution:
    def searchRange(self, nums: list[int], target: int) -> list[int]:
        N = len(nums)

        def LeftBoundary():
            # Инициализируем левую границу поиска (начало массива)
            lo = 0
            # Инициализируем правую границу поиска (конец массива)
            hi = N - 1
            # Переменная для хранения ответа, -1 означает что элемент не найден
            ans = -1

            # Бинарный поиск пока границы не пересекутся
            while lo <= hi:
                # Находим средний индекс (защита от переполнения)
                mi = lo + (hi - lo) // 2

                if nums[mi] < target:
                    # Если средний элемент меньше target, ищем в правой половине
                    lo = mi + 1
                elif nums[mi] > target:
                    # Если средний элемент больше target, ищем в левой половине
                    hi = mi - 1
                else:
                    # Нашли target! Запоминаем позицию
                    ans = mi
                    # Продолжаем поиск влево, чтобы найти самое первое вхождение
                    hi = mi - 1

            # Возвращаем индекс первого вхождения target (или -1 если не найден)
            return ans

        def RightBoundary():
            # Инициализируем левую границу поиска (начало массива)
            lo = 0
            # Инициализируем правую границу поиска (конец массива)
            hi = N - 1
            # Переменная для хранения ответа, -1 означает что элемент не найден
            ans = -1

            # Бинарный поиск пока границы не пересекутся
            while lo <= hi:
                # Находим средний индекс (защита от переполнения)
                mi = lo + (hi - lo) // 2

                if nums[mi] < target:
                    # Если средний элемент меньше target, ищем в правой половине
                    lo = mi + 1
                elif nums[mi] > target:
                    # Если средний элемент больше target, ищем в левой половине
                    hi = mi - 1
                else:
                    # Нашли target! Запоминаем позицию
                    ans = mi
                    # Продолжаем поиск вправо, чтобы найти самое последнее вхождение
                    lo = mi + 1

            # Возвращаем индекс последнего вхождения target (или -1 если не найден)
            return ans

        # Возвращаем массив из двух элементов: [первая позиция, последняя позиция]
        return [LeftBoundary(), RightBoundary()]
