class Solution:
    def arrangeCoins(self, n: int) -> int:
        # Вспомогательная функция для проверки, можно ли построить 'val' полных рядов
        # Формула val * (val + 1) // 2 вычисляет общее количество монет,
        # необходимое для построения 'val' рядов (сумма арифметической прогрессии)
        def IsGood(val):
            # Возвращаем True, если для 'val' рядов нужно не более n монет
            return val * (val + 1) // 2 <= n

        # Инициализируем левую границу поиска (минимальное количество рядов)
        lo = 0

        # Инициализируем правую границу поиска (максимально возможное количество рядов)
        # 2**32 - достаточно большое число для ограничения поиска
        hi = 2**32
        # hi = n
        # hi = ( n + 1 ) // 2

        # Переменная для хранения ответа (наибольшее подходящее значение)
        ans = -1

        # Бинарный поиск для нахождения максимального количества полных рядов
        while lo <= hi:
            # Находим средний элемент (защита от переполнения)
            mi = lo + (hi - lo) // 2

            if IsGood(mi):
                # Если можно построить 'mi' рядов, запоминаем это значение
                # и пробуем увеличить количество рядов (ищем максимум)
                ans = mi
                lo = mi + 1
            else:
                # Если нельзя построить 'mi' рядов (нужно больше монет, чем есть),
                # уменьшаем верхнюю границу поиска
                hi = mi - 1

        # Возвращаем максимальное количество полных рядов, которое можно построить
        return ans
