class Solution:
    def findPeakElement(self, nums: list[int]) -> int:
        # Инициализируем границы поиска
        lo = 0
        hi = len(nums) - 1

        # Бинарный поиск пикового элемента
        while lo < hi:
            # Находим средний индекс
            mi = lo + (hi - lo) // 2

            # Сравниваем средний элемент с правым соседом
            if nums[mi] < nums[mi + 1]:
                # Если nums[mi] < nums[mi+1], значит массив "растёт" вправо.
                # Поскольку за пределами массива значения равны -∞,
                # пик обязательно находится в правой половине (mi+1 ... hi).
                # Поэтому сдвигаем левую границу на mi + 1.
                lo = mi + 1
            else:
                # Если nums[mi] >= nums[mi+1], значит массив "убывает" вправо.
                # Пик находится в левой половине, включая сам mi.
                # Поэтому сдвигаем правую границу на mi (не mi-1, т.к. mi может быть пиком).
                hi = mi

        # Когда lo == hi, мы сошлись в одной точке — это и есть пик
        return lo
