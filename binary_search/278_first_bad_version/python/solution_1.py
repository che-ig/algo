class Solution:
    def firstBadVersion(self, n: int) -> int:
        # Задаем границы поиска: от первой версии до n-й
        left, right = 1, n

        # Продолжаем поиск, пока границы не сойдутся в одной точке
        while left < right:
            # Вычисляем среднюю точку.
            # Формула left + (right - left) // 2 используется для предотвращения
            # переполнения целого числа (актуально для языков вроде C++ или Java,
            # в Python это просто хорошая практика).
            mid = left + (right - left) // 2

            if isBadVersion(mid):
                # Если версия mid плохая, значит первая плохая версия — это mid
                # или она находится где-то до неё (в левой половине).
                # Мы сдвигаем правую границу на mid, не исключая сам mid из поиска.
                right = mid
            else:
                # Если версия mid хорошая, значит все версии до неё тоже хорошие.
                # Первая плохая версия находится строго после mid (в правой половине).
                # Мы сдвигаем левую границу на mid + 1, исключая mid из поиска.
                left = mid + 1

        # Когда left == right, диапазон поиска сузился до одного элемента.
        # Это и есть первая плохая версия.
        return left
