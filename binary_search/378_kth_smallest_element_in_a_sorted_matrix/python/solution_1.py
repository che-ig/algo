class Solution:
    def kthSmallest(self, matrix: list[list[int]], k: int) -> int:
        n = len(matrix)

        # Левая и правая границы поиска (минимальное и максимальное значения в матрице)
        lo = matrix[0][0]
        hi = matrix[-1][-1]

        def count_less_equal(mid: int) -> int:
            """
            Считает количество элементов в матрице, которые <= mid.
            Используем свойство отсортированности строк и столбцов.
            Начинаем с левого нижнего угла и двигаемся "лесенкой".
            """
            count = 0
            row = n - 1  # Начинаем с последней строки
            col = 0  # Начинаем с первого столбца

            while row >= 0 and col < n:
                if matrix[row][col] <= mid:
                    # Если текущий элемент <= mid, то все элементы ВЫШЕ него
                    # в этом же столбце тоже <= mid (т.к. столбец отсортирован).
                    # Добавляем их количество (row + 1) и двигаемся вправо.
                    count += row + 1
                    col += 1
                else:
                    # Если элемент > mid, двигаемся вверх, чтобы уменьшить значение
                    row -= 1

            return count

        # Бинарный поиск
        while lo < hi:
            mid = lo + (hi - lo) // 2

            # Считаем, сколько элементов <= mid
            if count_less_equal(mid) < k:
                # Если элементов меньше k, значит k-й элемент точно больше mid.
                # Сдвигаем левую границу.
                lo = mid + 1
            else:
                # Если элементов >= k, значит k-й элемент <= mid.
                # mid может быть ответом, поэтому сдвигаем правую границу на mid.
                hi = mid

        # Когда lo == hi, мы нашли точное значение k-го элемента
        return lo


