class Solution:
    def kthSmallest(self, grid: list[list[int]], k: int) -> int:
        # Получаем размеры матрицы
        # M — количество строк, N — количество столбцов
        M = len(grid)
        N = len(grid[0])

        def IsGood(num) -> int:
            """
            Считает количество элементов в матрице, которые <= num.
            Использует "метод лесенки" (staircase approach) для подсчета за O(M + N).

            Начинаем с ЛЕВОГО НИЖНЕГО УГЛА матрицы.
            Благодаря отсортированности строк и столбцов:
            - Если grid[i][j] <= num, то ВСЕ элементы выше в этом столбце
              (от 0 до i) тоже <= num. Добавляем их количество (i + 1)
              и двигаемся ВПРАВО.
            - Если grid[i][j] > num, двигаемся ВВЕРХ, чтобы уменьшить значение.

            Args:
                num: число, относительно которого считаем элементы

            Returns:
                Количество элементов в матрице, которые <= num
            """
            # Начинаем с последней строки (нижний ряд)
            i = M - 1
            # Начинаем с первого столбца (левый край)
            j = 0
            # Счётчик элементов, которые <= num
            total = 0

            # Двигаемся "лесенкой" пока не выйдем за границы матрицы
            while i >= 0 and j < N:
                if grid[i][j] <= num:
                    # Текущий элемент <= num.
                    # Поскольку столбец отсортирован по возрастанию,
                    # ВСЕ элементы выше (от 0 до i включительно) тоже <= num.
                    # Их количество: i + 1 (индексы 0, 1, ..., i)
                    total += i + 1
                    # Двигаемся вправо, чтобы проверить следующий столбец
                    j += 1
                else:
                    # Текущий элемент > num.
                    # Двигаемся вверх, чтобы найти меньшие элементы
                    i -= 1

            return total

        # Инициализируем границы бинарного поиска по ЗНАЧЕНИЯМ (не индексам!)
        # lo — минимальное значение в матрице (левый верхний угол)
        lo = grid[0][0]
        # hi — максимальное значение в матрице (правый нижний угол)
        hi = grid[-1][-1]
        # Переменная для хранения ответа (k-го наименьшего элемента)
        # Инициализируем минимальным значением
        ans = lo

        # Бинарный поиск для нахождения k-го наименьшего элемента
        # Ищем ПЕРВОЕ значение, для которого IsGood(mi) >= k
        while lo <= hi:
            # Находим середину текущего диапазона значений
            # Формула lo + (hi - lo) // 2 защищает от переполнения
            mi = lo + (hi - lo) // 2

            if IsGood(mi) >= k:
                # Если элементов <= mi как минимум k штук,
                # значит k-й наименьший элемент <= mi.
                # Запоминаем mi как потенциальный ответ
                ans = mi
                # Пробуем найти меньшее значение (сдвигаем правую границу)
                hi = mi - 1
            else:
                # Если элементов <= mi меньше k,
                # значит k-й элемент > mi.
                # Сдвигаем левую границу вправо
                lo = mi + 1

        # Возвращаем найденный k-й наименьший элемент
        return ans
