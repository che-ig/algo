class Solution:
    def findMin(self, nums: list[int]) -> int:
        # Получаем длину массива
        N = len(nums)

        # Инициализируем левую границу поиска (начало массива)
        lo = 0

        # Инициализируем правую границу поиска (конец массива)
        hi = N - 1

        # Переменная для хранения индекса минимального элемента
        ans = -1

        # Бинарный поиск для нахождения минимального элемента
        # в отсортированном повёрнутом массиве
        while lo <= hi:
            # Находим средний индекс (защита от переполнения)
            mi = lo + (hi - lo) // 2

            if nums[mi] < nums[-1]:
                # Если средний элемент меньше последнего элемента массива,
                # значит минимальный элемент находится на позиции mi или левее.
                # Запоминаем текущую позицию как возможный ответ
                # и продолжаем поиск в левой половине
                ans = mi
                hi = mi - 1
            elif nums[mi] > nums[-1]:
                # Если средний элемент больше последнего элемента массива,
                # значит мы находимся в левой (большой) части повёрнутого массива.
                # Минимальный элемент находится правее, поэтому
                # сдвигаем левую границу вправо
                lo = mi + 1
            else:
                # Если nums[mi] == nums[-1], это значит что мы нашли
                # элемент равный последнему. Запоминаем позицию
                # и продолжаем поиск влево (на случай дубликатов)
                ans = mi
                hi = mi - 1

        # Возвращаем минимальный элемент по найденному индексу
        return nums[ans]
