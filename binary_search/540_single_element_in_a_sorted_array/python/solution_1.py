"""
# Проверка на чётность
if x & 1 == 0:   # x чётное
if x & 1 == 1:   # x нечётное

# Или короче (в Python 0 = False, 1 = True):
if x & 1:        # x нечётное
if not x & 1:    # x чётное
"""


class Solution:
    def singleNonDuplicate(self, nums: list[int]) -> int:
        N = len(nums)

        def good(idx):
            """
            Проверяет, находится ли индекс idx ДО уникального элемента.
            Возвращает True, если на позиции idx всё ещё действует
            закономерность: пары начинаются на чётных индексах.
            Возвращает False, если мы достигли или перешли уникальный элемент.
            """
            # На последнем элементе всегда False (там уникальный элемент)
            if idx == N - 1:
                return False

            # Если индекс чётный, проверяем, равен ли он следующему элементу
            # (правильная пара: [чётный, нечётный])
            if idx % 2 == 0:
                return nums[idx] == nums[idx + 1]

            # Если индекс нечётный, проверяем, равен ли он предыдущему элементу
            # (правильная пара: [чётный, нечётный])
            return nums[idx] == nums[idx - 1]

        lo = 0
        hi = N - 1
        ans = -1

        while lo <= hi:
            mi = lo + (hi - lo) // 2

            if good(mi):
                # Если на позиции mi всё ещё "хорошо" (пары правильные),
                # значит уникальный элемент находится правее.
                # Запоминаем mi как границу и идём вправо.
                ans = mi
                lo = mi + 1
            else:
                # Если закономерность нарушена, значит уникальный элемент
                # находится на позиции mi или левее.
                # Ищем первое нарушение, двигаясь влево.
                hi = mi - 1

        # ans - это последний индекс, где ещё всё "хорошо"
        # Значит уникальный элемент находится на ans + 1
        return nums[ans + 1]
