def missingElement(self, nums: list[int], k: int) -> int:
    # Вспомогательная функция для подсчёта количества пропущенных чисел
    # от начала массива (nums[0]) до индекса idx включительно
    def GetMissingCount(idx):
        # Сколько чисел ДОЛЖНО БЫТЬ в диапазоне от nums[0] до nums[idx]
        # если бы не было пропусков.
        # Например: nums[0]=4, nums[idx]=10 → должно быть 10-4+1=7 чисел: [4,5,6,7,8,9,10]
        total_with_missed = nums[idx] - nums[0] + 1

        # Сколько чисел ЕСТЬ на самом деле от индекса 0 до idx
        # Например: если idx=2, то элементов 3 (индексы 0, 1, 2)
        actual_elements = idx + 1

        # Разница между ожидаемым количеством и фактическим — это количество пропусков
        # Например: должно быть 7 чисел, а есть 3 → пропущено 4 числа
        return total_with_missed - actual_elements
        # return nums[i] - nums[0] - i

    # Левая граница бинарного поиска (начало массива)
    lo = 0

    # Правая граница бинарного поиска (конец массива)
    hi = len(nums) - 1

    # Переменная для хранения индекса, до которого пропущено меньше k чисел
    ans = 0

    # Бинарный поиск для нахождения последнего индекса,
    # где количество пропущенных чисел меньше k
    while lo <= hi:
        # Находим средний индекс (формула защищает от переполнения)
        mi = lo + (hi - lo) // 2

        if GetMissingCount(mi) < k:
            # Если до индекса mi пропущено меньше k чисел,
            # значит k-е пропущенное число находится ПРАВЕЕ
            # Запоминаем текущий индекс как потенциальный ответ
            # и продолжаем поиск вправо
            ans = mi
            lo = mi + 1
        else:
            # Если до индекса mi пропущено >= k чисел,
            # значит k-е пропущенное число находится ЛЕВЕЕ
            # Сдвигаем правую границу влево
            hi = mi - 1

    # Вычисляем k-е пропущенное число:
    # nums[ans] — значение в найденной позиции
    # GetMissingCount(ans) — сколько чисел пропущено до этой позиции
    # k - GetMissingCount(ans) — сколько ещё чисел нужно добавить после nums[ans]
    #
    # Правильный пример: nums = [4,7,9,10], k = 3
    # Пропущенные числа: [5, 6, 8, ...]
    # ans = 1 (индекс элемента 7), GetMissingCount(1) = 2 (пропущены 5, 6)
    # Ответ: 7 + (3 - 2) = 7 + 1 = 8 ✓
    return nums[ans] + k - GetMissingCount(ans)
