import sys

# Увеличиваем лимит рекурсии, так как DFS может уйти вглубь на N уровней
# (например, если дерево вырождено в бамбук).
sys.setrecursionlimit(300000)


class SegmentTree:
    """Простое итеративное Дерево отрезков (Point Update, Range Sum Query)."""

    def __init__(self, data: list[int]) -> None:
        """
        Инициализирует дерево отрезков на основе исходного массива данных.

        Args:
            data: Исходный список целых чисел, на котором будет построено дерево.
        """
        self.n = len(data)
        # Массив дерева отрезков. Размер 2*n позволяет хранить и листья, и внутренние узлы.
        # Листья (исходные данные) начинаются с индекса n.
        self.tree = [0] * (2 * self.n)
        self.build(data)

    def build(self, data: list[int]) -> None:
        """
        Строит дерево отрезков снизу вверх за O(n), заполняя внутренние узлы суммами.

        Args:
            data: Исходный список целых чисел для инициализации листьев дерева.
        """
        for i in range(self.n):
            self.tree[self.n + i] = data[i]
        for i in range(self.n - 1, 0, -1):
            self.tree[i] = self.tree[2 * i] + self.tree[2 * i + 1]

    def update(self, pos: int, value: int) -> None:
        """
        Обновляет значение в конкретной позиции и пересчитывает суммы во всех затронутых родительских узлах.

        Args:
            pos: Индекс обновляемого элемента в исходном массиве (0-indexed).
            value: Новое целочисленное значение, которое нужно записать в позицию pos.
        """
        pos += self.n
        self.tree[pos] = value
        while pos > 1:
            self.tree[pos >> 1] = self.tree[pos] + self.tree[pos ^ 1]
            pos >>= 1

    def query(self, l: int, r: int) -> int:
        """
        Вычисляет сумму элементов на заданном отрезке [l, r].

        Args:
            l: Левая граница отрезка (включительно, 0-indexed).
            r: Правая граница отрезка (включительно, 0-indexed).

        Returns:
            Сумма всех элементов на отрезке от l до r.
        """
        res = 0
        l += self.n
        r += self.n + 1
        while l < r:
            if l & 1:
                res += self.tree[l]
                l += 1
            if r & 1:
                r -= 1
                res += self.tree[r]
            l >>= 1
            r >>= 1
        return res


class HLD:
    """
    Heavy-Light Decomposition (Тяжёло-лёгкое разложение).
    Разбивает дерево на непересекающиеся тяжёлые цепи так, чтобы любой путь
    между двумя вершинами пересекал не более O(log N) цепей.
    """

    def __init__(
        self,
        n: int,
        edges: list[tuple[int, int]],
        initial_values: list[int],
        root: int = 0,
    ) -> None:
        """
        Инициализирует структуру HLD, выполняет два обхода DFS для линеаризации
        дерева и строит внутреннее дерево отрезков.

        Args:
            n: Количество вершин в дереве.
            edges: Список рёбер дерева, где каждое ребро представлено кортежем (u, v).
            initial_values: Список начальных значений (весов) для каждой вершины дерева.
            root: Индекс корневой вершины дерева, от которой будут считаться глубины (по умолчанию 0).
        """
        self.n = n  # Количество вершин в дереве

        # Список смежности: хранит рёбра дерева (неориентированный граф)
        self.adj: list[list[int]] = [[] for _ in range(n)]
        for u, v in edges:
            self.adj[u].append(v)
            self.adj[v].append(u)

        self.values = initial_values  # Исходные веса/значения в вершинах
        self.root = root  # Индекс корневой вершины

        # --- Атрибуты, заполняемые в первом DFS (подготовка структуры) ---

        # parent[v]: родитель вершины v. Нужен, чтобы "подниматься" по дереву к корню.
        self.parent = [-1] * n

        # depth[v]: глубина вершины v (расстояние от корня).
        # Нужен, чтобы понимать, какая из двух вершин находится ниже.
        self.depth = [0] * n

        # sz[v]: размер поддерева с корнем в v (количество вершин в поддереве).
        # Нужен для определения "тяжёлого" ребёнка.
        self.sz = [1] * n  # Изначально каждая вершина имеет размер 1 (сама себя)

        # heavy[v]: индекс "тяжёлого" ребёнка вершины v.
        # Тяжёлый ребёнок — это ребёнок, чьё поддерево имеет максимальный размер.
        # Если -1, значит у вершины нет детей (лист).
        self.heavy = [-1] * n

        # --- Атрибуты, заполняемые во втором DFS (линеаризация) ---

        # pos[v]: позиция вершины v в линеаризованном (выпрямленном) массиве.
        # Именно по этому индексу вершина будет храниться в Дереве отрезков.
        self.pos = [0] * n

        # top[v]: "голова" (самая верхняя вершина) тяжёлой цепи, которой принадлежит v.
        # Нужен, чтобы быстро прыгать между цепями при запросе пути.
        self.top = [0] * n

        # cur_pos: счётчик, который инкрементируется при обходе DFS2.
        # Гарантирует, что вершины одной цепи получат подряд идущие индексы.
        self.cur_pos = 0

        # Запускаем два прохода DFS для вычисления всех атрибутов
        self._dfs1(root, -1)
        self._dfs2(root, root)

        # Собираем плоский массив значений в том порядке, который задал DFS2
        seg_data = [0] * n
        for i in range(n):
            seg_data[self.pos[i]] = self.values[i]

        # Создаём дерево отрезков на основе линеаризованного массива
        self.seg = SegmentTree(seg_data)

    def _dfs1(self, v: int, p: int) -> None:
        """
        Первый обход в глубину (DFS).
        Вычисляет размеры поддеревьев, глубины вершин и находит тяжёлого ребёнка для каждой вершины.

        Args:
            v: Текущая посещаемая вершина.
            p: Индекс родительской вершины для v (нужен, чтобы избежать возврата назад по ребру).
        """
        self.parent[v] = p
        max_subtree_size = 0

        for to in self.adj[v]:
            if to != p:
                self.depth[to] = self.depth[v] + 1
                self._dfs1(to, v)
                self.sz[v] += self.sz[to]

                # Если поддерево этого ребёнка больше предыдущего максимума,
                # делаем его тяжёлым ребёнком
                if self.sz[to] > max_subtree_size:
                    max_subtree_size = self.sz[to]
                    self.heavy[v] = to

    def _dfs2(self, v: int, up: int) -> None:
        """
        Второй обход в глубину (DFS).
        Линеаризует дерево: присваивает позиции в массиве и определяет голову тяжёлой цепи.
        Тяжёлый ребёнок обходится первым, чтобы его цепь получила непрерывные индексы.

        Args:
            v: Текущая посещаемая вершина.
            up: Индекс вершины, являющейся головой (верхней точкой) текущей тяжёлой цепи.
        """
        # Присваиваем текущую позицию и запоминаем голову цепи
        self.pos[v] = self.cur_pos
        self.top[v] = up
        self.cur_pos += 1

        # КРИТИЧЕСКИ ВАЖНО: сначала идём в тяжёлого ребёнка.
        # Благодаря этому вся тяжёлая цепь получит подряд идущие индексы (pos).
        # Голова цепи (up) при этом не меняется.
        if self.heavy[v] != -1:
            self._dfs2(self.heavy[v], up)

        # Затем идём в лёгких детей.
        # Каждый лёгкий ребёнок начинает НОВУЮ тяжёлую цепь,
        # поэтому он сам становится её головой (передаём to вместо up).
        for to in self.adj[v]:
            if to != self.parent[v] and to != self.heavy[v]:
                self._dfs2(to, to)

    def update_vertex(self, v: int, new_value: int) -> None:
        """
        Обновляет значение (вес) конкретной вершины в дереве.

        Args:
            v: Индекс вершины, значение которой нужно обновить.
            new_value: Новое целочисленное значение для вершины v.
        """
        # Находим позицию вершины в линеаризованном массиве и обновляем дерево отрезков
        self.seg.update(self.pos[v], new_value)

    def query_path(self, u: int, v: int) -> int:
        """
        Вычисляет сумму значений на простом пути между двумя вершинами u и v.
        Разбивает путь на O(log N) непрерывных отрезков тяжёлых цепей и запрашивает их суммы.

        Args:
            u: Индекс первой вершины пути.
            v: Индекс второй вершины пути.

        Returns:
            Сумма значений всех вершин, лежащих на пути между u и v.
        """
        res = 0

        # Пока u и v находятся в разных тяжёлых цепях (их "головы" не совпадают)
        while self.top[u] != self.top[v]:
            # Выбираем ту вершину, чья голова цепи находится глубже (ниже в дереве).
            # Её мы будем "поднимать" к корню.
            if self.depth[self.top[u]] < self.depth[self.top[v]]:
                u, v = v, u  # Меняем местами, чтобы u всегда была "ниже"

            # u теперь глубже. Берём сумму по всей тяжёлой цепи от головы до u.
            # В линеаризованном массиве это непрерывный отрезок [pos[top[u]], pos[u]]
            res += self.seg.query(self.pos[self.top[u]], self.pos[u])

            # Прыгаем на вершину, которая является родителем головы цепи.
            # Таким образом мы переходим в другую (более высокую) цепь.
            u = self.parent[self.top[u]]

        # Когда цикл завершился, u и v находятся в ОДНОЙ тяжёлой цепи.
        # Осталось взять сумму между ними.
        # В линеаризованном массиве вершина с меньшей глубиной будет иметь меньший индекс pos.
        if self.depth[u] > self.depth[v]:
            u, v = v, u  # u теперь выше (ближе к корню), v ниже

        res += self.seg.query(self.pos[u], self.pos[v])
        return res


