class SegmentTreeSum:
    """
    Итеративное дерево отрезков для суммы.

    Массив tree имеет размер 2*n.
    Листья: tree[n], tree[n+1], ..., tree[2n-1]
    Внутренние узлы: tree[1], tree[2], ..., tree[n-1]
    """

    def __init__(self, arr: list[int]) -> None:
        """
        Построение дерева отрезков за O(N).

        Args:
            arr: Исходный массив (0-индексация)
        """
        self.n = len(arr)
        self.tree = [0] * (2 * self.n)

        # Копируем листья
        for i in range(self.n):
            self.tree[self.n + i] = arr[i]

        # Строим внутренние узлы снизу вверх
        for i in range(self.n - 1, 0, -1):
            self.tree[i] = self.tree[2 * i] + self.tree[2 * i + 1]

    def update(self, pos: int, value: int) -> None:
        """
        Устанавливает значение arr[pos] = value.
        Время: O(log N)

        Args:
            pos: Индекс элемента (0-индексация)
            value: Новое значение
        """
        # Переходим к соответствующему листу
        pos += self.n

        # Обновляем лист
        self.tree[pos] = value

        # Поднимаемся вверх, обновляя предков
        while pos > 1:
            pos //= 2
            self.tree[pos] = self.tree[2 * pos] + self.tree[2 * pos + 1]

    def query(self, left: int, right: int) -> int:
        """
        Возвращает сумму на отрезке [left, right].
        Время: O(log N)

        Args:
            left: Левая граница (0-индексация, включительно)
            right: Правая граница (0-индексация, включительно)

        Returns:
            Сумма элементов arr[left] + ... + arr[right]
        """
        # Переходим к листьям
        left += self.n
        right += self.n

        result = 0

        # Двигаемся вверх, пока не встретимся
        while left <= right:
            # Если left — правый ребёнок, добавляем его и двигаемся вправо
            if left % 2 == 1:
                result += self.tree[left]
                left += 1

            # Если right — левый ребёнок, добавляем его и двигаемся влево
            if right % 2 == 0:
                result += self.tree[right]
                right -= 1

            # Переходим к родителям
            left //= 2
            right //= 2

        return result


def run_tests() -> None:
    """Классические тест-кейсы для проверки корректности работы дерева."""

    # Массив с картинки (n = 15, не степень двойки — отличный стресс-тест)
    arr = [10, -7, 12, 2, 6, 5, -4, 8, -1, 1, 9, -2, 0, 3, 7]
    st = SegmentTreeSum(arr)

    print("🚀 Запуск тестов для SegmentTreeSum...")
    print(f"Исходный массив: {arr}\n")

    assert st.query(1, 8) == 21, "Ошибка: левый край"
    # 1. Тесты на одиночные элементы (границы и середина)
    assert st.query(0, 0) == 10, "Ошибка: левый край"
    assert st.query(1, 1) == -7, "Ошибка: отрицательный элемент"
    assert st.query(14, 14) == 7, "Ошибка: правый край"
    print("✅ Тесты одиночных элементов пройдены")

    # 2. Тесты на весь массив и префиксы/суффиксы
    assert st.query(0, 14) == 49, "Ошибка: сумма всего массива"
    assert st.query(0, 5) == 28, "Ошибка: префикс [0..5]"  # 10-7+12+2+6+5 = 28
    assert st.query(10, 14) == 17, "Ошибка: суффикс [10..14]"  # 9-2+0+3+7 = 17
    print("✅ Тесты префиксов, суффиксов и полного массива пройдены")

    # 3. Тесты на специфические случаи (отрицательный и нулевой результат)
    assert st.query(11, 12) == -2, "Ошибка: отрицательная сумма (-2 + 0)"
    assert st.query(8, 9) == 0, "Ошибка: нулевая сумма (-1 + 1)"
    print("✅ Тесты на отрицательные и нулевые суммы пройдены")

    # 4. Тесты на обновление (update)
    st.update(
        12, 5
    )  # Меняем arr[12] с 0 на 5. Общая сумма должна вырасти на 5 (49 -> 54)
    assert st.query(12, 12) == 5, "Ошибка: обновление листа"
    assert st.query(0, 14) == 54, "Ошибка: обновление затронуло корень"
    assert st.query(10, 14) == 22, "Ошибка: обновление затронуло суффикс (17 + 5)"
    print("✅ Тесты обновления (update) пройдены")

    # 5. Тест на некорректный диапазон (left > right)
    # В данной реализации цикл просто не выполнится, и вернется нейтральный элемент (0)
    assert st.query(5, 3) == 0, "Ошибка: некорректный диапазон должен возвращать 0"
    print("✅ Тест на некорректный диапазон (left > right) пройден")

    # 6. Сравнение с "наивным" решением (brute force) для всех возможных отрезков
    for l in range(len(arr)):
        for r in range(l, len(arr)):
            expected = sum(arr[l : r + 1])
            # Учитываем, что мы сделали один update выше (arr[12] = 5)
            test_arr = arr.copy()
            test_arr[12] = 5
            expected = sum(test_arr[l : r + 1])

            assert st.query(l, r) == expected, (
                f"Ошибка на отрезке [{l}, {r}]: ожидалось {expected}, получено {st.query(l, r)}"
            )
    print("✅ Полный перебор всех 120 отрезков совпал с наивным решением (sum)")

    print("\n🎉 Все тесты успешно пройдены! Дерево отрезков работает корректно.")


if __name__ == "__main__":
    run_tests()
