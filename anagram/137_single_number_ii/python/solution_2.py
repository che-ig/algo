class Solution:
    def singleNumber(self, nums):
        result = 0

        # Проходим по всем 32 битам (для 32-битного знакового числа)
        for i in range(32):
            # Считаем, сколько чисел имеют i-й бит установленным
            bit_sum = 0
            for num in nums:
                # Извлекаем i-й бит: сдвигаем вправо на i и берём младший бит
                bit_sum += (num >> i) & 1

            # Если сумма не кратна 3 — этот бит есть в ответе
            if bit_sum % 3 != 0:
                result |= 1 << i  # Устанавливаем i-й бит в result

        # Обработка отрицательных чисел (дополнительный код)
        # Если 31-й бит (знаковый) установлен — число отрицательное
        if result >= 2**31:
            result -= 2**32

        return result
