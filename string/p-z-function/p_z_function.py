"""
prefix_z.py — префикс-функция (π) и Z-функция: реализация, тесты, применение.
Требует Python 3.9+ (аннотации list[int]).
"""

from __future__ import annotations

import random
import time


# ==========================================================================
# 1. ПРЕФИКС-ФУНКЦИЯ
# ==========================================================================
def prefix_function(s: str) -> list[int]:
    """
    π[i] = длина наибольшего СОБСТВЕННОГО префикса s[0..i],
           который одновременно является его суффиксом.
    «Собственный» = короче всей подстроки, поэтому 0 <= π[i] <= i.

    Инвариант внутри цикла:
        перед обработкой позиции i переменная j = π[i-1],
        т.е. s[0..j-1] == s[i-j..i-1]  (префикс «натянут» на конец).
    Мы пытаемся продлить это совпадение на один символ:
        сравниваем s[i] с s[j] (следующий символ префикса).

    Если не совпало — берём следующий по длине бордер того же префикса:
        π[j-1]. Это корректно, потому что ANY бордер суффикса s[0..i-1]
        является бордером и для s[0..i] с меньшим размером, а π[j-1] —
        наибольший из бордеров префикса длины j, значит именно он — кандидат №1.
    """
    n = len(s)
    pi = [0] * n
    # π[0] = 0 всегда: у односимвольной строки собственного префикса нет.

    for i in range(1, n):
        j = pi[i - 1]  # длина лучшего совпадения для i-1

        # Откат по цепочке бордеров, пока не найдём продолжение.
        # Каждый шаг строго уменьшает j -> суммарно не больше n уменьшений.
        while j > 0 and s[i] != s[j]:
            j = pi[j - 1]

        if s[i] == s[j]:  # при j == 0 это сравнение s[i] с s[0]
            j += 1  # (безопасно: i >= 1, s[0] существует)

        pi[i] = j

    return pi


# Почему O(n): j растёт не более чем на 1 за итерацию внешнего цикла (<= n всего),
# а while только уменьшает j и j >= 0 => суммарное число итераций while <= n.


# ==========================================================================
# 2. Z-ФУНКЦИЯ
# ==========================================================================
def z_function(s: str) -> list[int]:
    """
    z[i] = длина наибольшего общего префикса строки s и её суффикса,
           начинающегося в позиции i.   z[0] := n (соглашение; см. заметку ниже).

    Инвариант: [l, r) — самый правый из найденных отрезков, совпадающих
    с префиксом строки: s[l..r-1] == s[0..r-l-1], при этом r максимально.

    Для i < r мы уже «знаем» ответ не хуже, чем z[i-l]:
    символы s[i..r-1] в точности равны s[i-l..r-1-l], а это префикс.
    Но за пределы rour мы выйти не можем, поэтому берём минимум с r-i.
    Дальше добираем совпадение «в лоб» и, если ушли правее, обновляем (l, r).
    """
    n = len(s)
    z = [0] * n
    if n == 0:
        return z

    z[0] = n  # соглашение: вся строка совпадает с собой.
    # Встречается и вариант z[0] = 0 — важно быть последовательным!

    l = r = 0  # r — «правая граница» (не включительно)
    for i in range(1, n):
        if i < r:
            # Используем уже посчитанное: симметричная позиция — i - l.
            z[i] = min(r - i, z[i - l])

        # Пробуем продлить. Каждый успешный шаг увеличивает r,
        # а r <= n => суммарно не больше n «в лоб» сравнений.
        while i + z[i] < n and s[z[i]] == s[i + z[i]]:
            z[i] += 1

        if i + z[i] > r:  # ушли правее — сдвигаем окно
            l, r = i, i + z[i]

    return z


# ==========================================================================
# 4. ТЕСТЫ
# ==========================================================================
def run_tests() -> None:
    # --- 4.1 Известные значения «в руках» ---------------------------------
    cases_pi = [
        ("", []),
        ("a", [0]),
        ("ab", [0, 0]),
        ("aa", [0, 1]),
        ("aaaa", [0, 1, 2, 3]),
        ("ababab", [0, 0, 1, 2, 3, 4]),
        ("abcabcd", [0, 0, 0, 1, 2, 3, 0]),
        ("aabaaab", [0, 1, 0, 1, 2, 2, 3]),  # кейс с несколькими откатами
        ("aaaaa", [0, 1, 2, 3, 4]),
    ]
    for s, expected in cases_pi:
        got = prefix_function(s)
        assert got == expected, f"π({s!r}) = {got}, ожидалось {expected}"

    cases_z = [
        ("", []),
        ("a", [1]),
        ("ab", [2, 0]),
        ("aa", [2, 1]),
        ("aaaa", [4, 3, 2, 1]),
        ("ababab", [6, 0, 4, 0, 2, 0]),
        ("abcabcd", [7, 0, 0, 3, 0, 0, 0]),
        ("aabaaab", [7, 1, 0, 2, 3, 1, 0]),
    ]
    for s, expected in cases_z:
        got = z_function(s)
        assert got == expected, f"z({s!r}) = {got}, ожидалось {expected}"

    # --- 4.2 Инварианты (самопроверка, без оракула) -----------------------
    s = "abracadabra"
    pi, z = prefix_function(s), z_function(s)
    for i in range(len(s)):
        # π: префикс длины pi[i] == суффиксу, заканчивающемуся в i
        k = pi[i]
        assert 0 <= k <= i
        assert s[:k] == s[i - k + 1 : i + 1]
        # z: префикс длины z[i] == подстроке, начинающейся в i
        assert 0 <= z[i] <= len(s) - i
        assert s[: z[i]] == s[i : i + z[i]]

    print("✅ Все тесты пройдены")


def bench(n: int = 1_000_000) -> None:
    """Демонстрация линейности: худший случай для обоих — 'aaaa...a'."""
    s = "a" * n
    for name, fn in (("prefix_function", prefix_function), ("z_function", z_function)):
        t = time.perf_counter()
        res = fn(s)
        dt = time.perf_counter() - t
        assert res[-1] == n - 1  # π: бордер полной длины минус 1
        assert res[1] == n - 1  # z: сдвиг на 1 даёт совпадение n-1
        print(f"   {name:<16} n={n:>9,} : {dt * 1000:7.1f} мс")


# ==========================================================================
# 5. ПРИМЕНЕНИЕ: поиск подстроки двумя способами
# ==========================================================================
def search_kmp(text: str, pattern: str) -> list[int]:
    """Кнута–Морриса–Пратта. π сообщает ПОЗИЦИЮ КОНЦА совпадения."""
    if not pattern:
        return []
    m = len(pattern)
    sep = "\x00"  # символ, которого нет в данных
    pi = prefix_function(pattern + sep + text)
    # Совпадение заканчивается в i => начинается в i-m+1 (в склейке),
    # а в text это (i - m + 1) - (m + 1) = i - 2m.
    return [i - 2 * m for i in range(len(pi)) if pi[i] == m]


def search_z(text: str, pattern: str) -> list[int]:
    """Z-алгоритм. z сообщает ПОЗИЦИЮ НАЧАЛА совпадения — на один шаг проще."""
    if not pattern:
        return []
    m = len(pattern)
    sep = "\x00"
    z = z_function(pattern + sep + text)
    return [i - (m + 1) for i in range(m + 1, len(z)) if z[i] == m]


def minimal_period(s: str) -> int:
    """Длина наименьшего блока, повторами которого получена s (если возможно)."""
    if not s:
        return 0
    p = len(s) - prefix_function(s)[-1]
    return p if len(s) % p == 0 else len(s)


def all_borders(s: str) -> list[int]:
    """Все бордеры строки (длины), убывающие. Классика «только для π»."""
    pi = prefix_function(s)
    res, k = [], pi[-1] if s else 0
    while k > 0:
        res.append(k)
        k = pi[k - 1]  # цепочка бордеров: бордер бордера — тоже бордер
    return res


if __name__ == "__main__":
    print("Тесты корректности:")
    run_tests()

    print("\nПроизводительность (худший случай):")
    bench()

    print("\nДемонстрация:")
    text, pat = "ababababab", "abab"
    print(f"  text={text!r}, pattern={pat!r}")
    print(f"  KMP (π): {search_kmp(text, pat)}")
    print(f"  Z-алг  : {search_z(text, pat)}")
    assert search_kmp(text, pat) == search_z(text, pat)

    print(f"  мин. период 'abcabcabc' = {minimal_period('abcabcabc')}")  # 3
    print(f"  бордеры  'ababab'       = {all_borders('ababab')}")  # [4, 2]
