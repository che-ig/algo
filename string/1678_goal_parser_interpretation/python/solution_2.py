class Solution:
    def interpret(self, command: str) -> str:
        """
        Интерпретирует команду Goal Parser.

        Ключевая идея: каждый токен заканчивается либо на 'G', либо на ')'.
        При встрече ')' смотрим на предыдущий символ:
          - '(' перед ')' означает токен "()"  → интерпретируем как 'o'
          - 'l' перед ')' означает токен "(al)" → интерпретируем как 'al'

        Символы '(', 'a', 'l' внутри токенов игнорируются —
        они не несут самостоятельной информации, вся нужная информация
        уже закодирована в последнем символе токена.
        """
        # Список для накопления символов результата.
        # Используем список вместо конкатенации строк,
        # так как ''.join(list) работает за O(n), а многократное + — за O(n²).
        result = []

        # Указатель на текущую позицию в строке command
        i = 0
        n = len(command)

        # Проходим по всем символам команды слева направо
        while i < n:
            # Случай 1: встретили 'G' — это самостоятельный токен.
            # Просто записываем 'G' в результат.
            if command[i] == "G":
                result.append("G")

            # Случай 2: встретили ')' — конец токена "()" или "(al)".
            # Смотрим на символ ПЕРЕД скобкой, чтобы определить, какой это токен.
            elif command[i] == ")":
                if command[i - 1] == "(":
                    # Перед ')' стоит '(' — значит это токен "()"
                    # Интерпретируем его как 'o'
                    result.append("o")
                elif command[i - 1] == "l":
                    # Перед ')' стоит 'l' — значит это токен "(al)"
                    # Интерпретируем его как 'al'
                    result.append("al")
                # Если перед ')' стоит что-то ещё — это невозможно по условию задачи,
                # так как command состоит только из токенов "G", "()", "(al)".

            # Случай 3: символ '(', 'a' или 'l'.
            # Эти символы являются частью токенов "()" или "(al)",
            # но вся нужная информация о токене уже учтена при обработке ')'.
            # Поэтому мы их просто игнорируем — ничего не добавляем в result.
            # Явный блок else здесь не нужен, так как нет действий.

            # Двигаем указатель вперёд в любом случае.
            # Выносим i += 1 за пределы условий, чтобы не дублировать код
            # в каждой ветке (принцип DRY — Don't Repeat Yourself).
            i += 1

        # Соединяем список символов в итоговую строку.
        # ''.join() — стандартный и эффективный способ конкатенации в Python.
        return "".join(result)
