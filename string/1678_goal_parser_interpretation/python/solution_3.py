class Solution:
    def interpret(self, command: str) -> str:
        """
        Интерпретирует команду Goal Parser через накопление символов в буфере.

        Идея: идём по строке посимвольно и накапливаем символы в переменной tmp.
        Как только tmp совпадает с одним из известных токенов ('G', '()', '(al)'),
        мы добавляем его интерпретацию в ответ и сбрасываем буфер.
        """
        # ans — итоговая интерпретированная строка.
        # Инициализируем пустой строкой, будем наращивать через конкатенацию.
        ans = ""

        # tmp — буфер для накопления символов текущего токена.
        # По мере чтения строки мы добавляем в него по одному символу,
        # пока он не совпадёт с одним из известных токенов.
        tmp = ""

        # Проходим по каждому символу команды
        for c in command:
            # Добавляем текущий символ в буфер токена
            tmp += c

            # Проверяем, не образовал ли буфер один из известных токенов.
            # Проверки идут от коротких к длинным, но это не критично,
            # так как токены не являются префиксами друг друга
            # (кроме '(' и '()', '(al)', но '(' сам по себе не токен).

            if tmp == "G":
                # Токен "G" распознан — добавляем его интерпретацию
                ans += "G"
                tmp = ""  # Сбрасываем буфер для следующего токена

            elif tmp == "()":
                # Токен "()" распознан — интерпретируем как 'o'
                ans += "o"
                tmp = ""  # Сбрасываем буфер

            elif tmp == "(al)":
                # Токен "(al)" распознан — интерпретируем как 'al'
                ans += "al"
                tmp = ""  # Сбрасываем буфер

        # Возвращаем итоговую интерпретированную строку.
        # По условию задачи command всегда корректен, поэтому tmp будет пустым.
        return ans
