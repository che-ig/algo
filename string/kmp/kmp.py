"""
Реализация алгоритма Кнута–Морриса–Пратта (KMP) для поиска всех вхождений
шаблона в текст.

Версия Python: 3.12
"""

from __future__ import annotations


def build_prefix_function(pattern: str) -> list[int]:
    """
    Строит префикс-функцию (LPS-массив) для шаблона.

    pi[i] — длина наибольшего собственного префикса подстроки pattern[:i+1],
    который одновременно является её суффиксом.

    Параметры:
        pattern: строка-шаблон, для которой строится префикс-функция.

    Возвращает:
        Список целых чисел длины len(pattern).

    Сложность: O(len(pattern)) по времени и памяти.
    """
    m: int = len(pattern)
    # pi[0] всегда 0: у строки длины 1 нет собственного непустого префикса-суффикса.
    pi: list[int] = [0] * m

    # j — длина текущего совпавшего префикса-суффикса для подстроки pattern[:i+1].
    j: int = 0
    # Начинаем с i = 1, так как pi[0] уже определён.
    for i in range(1, m):
        # Пока префикс и суффикс не совпадают, «откатываемся» назад
        # по уже вычисленным значениям префикс-функции.
        while j > 0 and pattern[i] != pattern[j]:
            j = pi[j - 1]

        # Если символы совпали — увеличиваем длину совпадающего префикса.
        if pattern[i] == pattern[j]:
            j += 1

        # Запоминаем результат для позиции i.
        pi[i] = j

    return pi


def kmp_search(text: str, pattern: str) -> list[int]:
    """
    Ищет все вхождения шаблона pattern в текст text с помощью алгоритма KMP.

    Параметры:
        text: строка, в которой ищем.
        pattern: строка-шаблон, которую ищем.

    Возвращает:
        Список индексов (0-based), с которых начинаются вхождения шаблона в текст.
        Если вхождений нет — пустой список.
        Если шаблон пуст — пустой список (по соглашению: пустой шаблон
        не считаем вхождением, чтобы избежать бесконечного числа совпадений).

    Сложность: O(len(text) + len(pattern)) по времени и O(len(pattern)) по памяти.
    """
    # Обработка вырожденных случаев.
    if not pattern or not text:
        return []
    if len(pattern) > len(text):
        return []

    n: int = len(text)
    m: int = len(pattern)

    # Префикс-функция для шаблона — центральная структура алгоритма.
    pi: list[int] = build_prefix_function(pattern)

    # matches — список стартовых позиций всех найденных вхождений.
    matches: list[int] = []

    # j — сколько символов шаблона уже совпало с текстом на текущий момент.
    j: int = 0
    # i — указатель по тексту; он только растёт — это гарантирует линейность.
    for i in range(n):
        # Пока не совпадает и есть куда откатываться — откатываемся по pi.
        while j > 0 and text[i] != pattern[j]:
            j = pi[j - 1]

        # Если текущий символ текста совпал с очередным символом шаблона.
        if text[i] == pattern[j]:
            j += 1

        # Если прошли весь шаблон — нашли вхождение.
        if j == m:
            # Начало вхождения: текущий i минус длина шаблона.
            matches.append(i - m + 1)
            # Продолжаем поиск: откатываемся, чтобы не пропустить пересекающиеся вхождения.
            j = pi[j - 1]

    return matches


# ---------------------------------------------------------------
# Пример использования
# ---------------------------------------------------------------
if __name__ == "__main__":
    text: str = "ABABDABACDABABCABAB"
    pattern: str = "ABABCABAB"

    pi: list[int] = build_prefix_function(pattern)
    print(f"Префикс-функция для {pattern!r}: {pi}")

    positions: list[int] = kmp_search(text, pattern)
    print(f"Вхождения {pattern!r} в {text!r}: {positions}")
    # Ожидаемый вывод: [10]

    # Несколько вхождений с пересечениями
    text2: str = "AAAAA"
    pattern2: str = "AA"
    print(f"Вхождения {pattern2!r} в {text2!r}: {kmp_search(text2, pattern2)}")
    # Ожидаемый вывод: [0, 1, 2, 3]
