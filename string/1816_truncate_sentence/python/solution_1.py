class Solution:
    def truncateSentence(self, s: str, k: int) -> str:
        """
        Возвращает первые k слов предложения s.

        Алгоритм: идём по строке и считаем пробелы.
        Когда встречаем k-й пробел, значит перед ним заканчиваются k слов.
        Возвращаем подстроку от начала до этого пробела.

        Если пробелов меньше k (то есть k равно общему числу слов),
        возвращаем всю строку целиком.
        """
        # space_count — счётчик встреченных пробелов
        space_count = 0

        # Проходим по всем символам строки с их индексами
        for i, char in enumerate(s):
            if char == " ":
                space_count += 1

                # Если встретили k-й пробел, значит перед ним ровно k слов.
                # Возвращаем подстроку от начала до этого пробела (не включая его).
                if space_count == k:
                    return s[:i]

        # Если цикл завершился и мы не нашли k-й пробел,
        # значит k равно общему числу слов в строке.
        # Возвращаем всю строку целиком.
        return s
