class Solution:
    def lengthOfLastWord(self, s: str) -> int:
        """
        Возвращает длину последнего слова в строке.

        Алгоритм: идём по строке справа налево в два этапа:
        1. Пропускаем все конечные пробелы (если они есть)
        2. Считаем символы последнего слова до первого пробела или начала строки

        :param s: входная строка, содержащая слова и пробелы
        :return: длина последнего слова
        """

        # Инициализируем указатель i на последний символ строки.
        # len(s) - 1 — это индекс последнего элемента (строки индексируются с 0).
        # Например, для строки "Hello World" (длина 11) i = 10.
        i = len(s) - 1

        # === ЭТАП 1: Пропускаем конечные пробелы ===
        # Двигаем указатель влево, пока встречаем пробелы.
        # Это нужно для обработки строк вида "moon  " (с пробелами в конце).
        #
        # Пример: s = "   fly me   to   the moon  "
        # Начальное i = 26 (последний пробел)
        # После цикла i = 24 (символ 'n' в слове "moon")
        #
        # ВАЖНО: по условию задачи в строке есть хотя бы одно слово,
        # поэтому цикл гарантированно остановится на букве и не выйдет за границы.
        while s[i] == " ":
            i -= 1

        # === ЭТАП 2: Считаем длину последнего слова ===
        # ans — счётчик символов последнего слова.
        # Инициализируем 0, будем увеличивать на 1 для каждого символа.
        ans = 0

        # Двигаем указатель влево, пока встречаем НЕ пробелы.
        # Каждый символ — это часть последнего слова, увеличиваем счётчик.
        #
        # Пример: s = "   fly me   to   the moon  "
        # Начинаем с i = 24 (символ 'n')
        # i=24: 'n' → ans=1, i=23
        # i=23: 'o' → ans=2, i=22
        # i=22: 'o' → ans=3, i=21
        # i=21: 'm' → ans=4, i=20
        # i=20: ' ' → выход из цикла
        #
        # Цикл остановится, когда встретит пробел (начало последнего слова)
        # или когда i станет отрицательным (если последнее слово — первое в строке).
        while s[i] != " ":
            ans += 1
            i -= 1

        # Возвращаем длину последнего слова
        return ans
