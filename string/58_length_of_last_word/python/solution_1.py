class Solution:
    def lengthOfLastWord(self, s: str) -> int:
        """
        Возвращает длину последнего слова в строке.
        Использует обратный проход для достижения O(1) по памяти.
        """
        # length — счётчик символов последнего слова.
        # Инициализируем 0.
        length = 0

        # Идём по строке с конца (справа налево).
        # range(len(s) - 1, -1, -1) генерирует индексы от последнего до 0.
        for i in range(len(s) - 1, -1, -1):
            char = s[i]

            # Если текущий символ — пробел
            if char == " ":
                # Если мы уже начали считать слово (length > 0),
                # значит, этот пробел отделяет последнее слово от предпоследнего.
                # Дальше идти нет смысла, прерываем цикл.
                if length > 0:
                    break
                # Если length == 0, значит мы всё ещё пропускаем
                # конечные пробелы строки (например, "moon  ").
                # Просто продолжаем цикл.
            else:
                # Если символ не пробел — это часть последнего слова.
                # Увеличиваем счётчик.
                length += 1

        return length
