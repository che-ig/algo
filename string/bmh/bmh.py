def boyer_moore_horspool_search(text: str, pattern: str) -> int:
    """
    Ищет первое вхождение подстроки (pattern) в строке (text)
    используя алгоритм Бойера-Мура-Хорспула.

    Алгоритм сравнивает символы справа налево и использует упрощенную
    эвристику "плохого символа" для сдвига шаблона.

    Args:
        text (str): Исходная строка, в которой осуществляется поиск.
        pattern (str): Искомая подстрока (шаблон).

    Returns:
        int: Индекс первого символа первого вхождения шаблона в тексте.
             Возвращает -1, если шаблон не найден.

    Raises:
        ValueError: Если pattern не является строкой.
    """
    if not isinstance(text, str) or not isinstance(pattern, str):
        raise ValueError("Оба аргумента должны быть строками (str).")

    n = len(text)
    m = len(pattern)

    # --- Обработка граничных случаев ---
    if m == 0:
        return 0  # Пустой шаблон считается найденным в начале
    if m > n:
        return -1  # Шаблон длиннее текста, искать негде

    # --- ЭТАП 1: Предобработка (создание таблицы сдвигов) ---
    # Мы создаем словарь, где для каждого символа шаблона (кроме самого последнего)
    # хранится расстояние от его правого вхождения до конца шаблона.
    # Если символа нет в словаре, сдвиг равен длине шаблона (m).
    shift_table: dict[str, int] = {}

    # Проходим по всем символам шаблона, КРОМЕ последнего (индекс m-1).
    # Это ключевая особенность BMH: мы всегда смотрим на символ текста,
    # который стоит напротив ПОСЛЕДНЕГО символа шаблона.
    for i in range(m - 1):
        # Перезаписываем значение, чтобы сохранить именно самое ПРАВОЕ вхождение.
        # Расстояние = (длина шаблона - 1) - текущий индекс
        shift_table[pattern[i]] = m - 1 - i

    # --- ЭТАП 2: Основной цикл поиска ---
    # i - это индекс в тексте, указывающий на КОНЕЦ текущего окна сравнения.
    # Начинаем с конца первого окна (индекс m - 1).
    i = m - 1

    while i < n:
        k = 0

        # Сравниваем шаблон с текстом СПРАВА НАЛЕВО.
        # k - это количество успешно совпавших символов.
        while k < m and pattern[m - 1 - k] == text[i - k]:
            k += 1

        # Если k равно длине шаблона, значит все символы совпали.
        if k == m:
            # Возвращаем индекс начала найденного окна в тексте
            return i - m + 1

        # --- Произошло несовпадение (или мы даже не начали сравнивать) ---
        # В BMH мы ВСЕГДА смотрим на символ текста, который находится
        # ровно напротив последнего символа шаблона (то есть на text[i]).
        bad_char = text[i]

        # Получаем величину сдвига из таблицы.
        # Если символа нет в таблице (его нет в шаблоне), сдвигаем шаблон
        # полностью за этот символ (на m позиций).
        shift = shift_table.get(bad_char, m)

        # Примечание: сдвиг всегда >= 1, так как в таблицу мы записывали
        # значения от 1 до m-1, а по умолчанию подставляем m.
        # Это гарантирует, что алгоритм никогда не зациклится.

        # Сдвигаем окно в тексте вправо
        i += shift

    # Если цикл завершился, а возврат внутри не сработал, значит совпадений нет.
    return -1


