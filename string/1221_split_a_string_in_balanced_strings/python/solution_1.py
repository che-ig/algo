class Solution:
    def balancedStringSplit(self, s: str) -> int:
        """
        Разбивает сбалансированную строку на максимальное количество
        сбалансированных подстрок.
        """
        # balance — текущий разбаланс.
        # Если balance == 0, количество 'R' и 'L' равно.
        balance = 0

        # count — количество найденных сбалансированных подстрок
        count = 0

        # Проходим по всем символам строки
        for char in s:
            # Если встречаем 'R', увеличиваем баланс
            if char == "R":
                balance += 1
            # Если встречаем 'L', уменьшаем баланс
            else:
                balance -= 1

            # Как только баланс стал 0, мы нашли очередную сбалансированную подстроку.
            # Жадно "отрезаем" её и начинаем считать следующую.
            if balance == 0:
                count += 1

        return count
