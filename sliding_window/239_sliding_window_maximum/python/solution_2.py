import heapq

"""
Плюсы: Проще для понимания, чем монотонная очередь.
Минусы: O(nlogk) вместо O(n); на больших k заметно медленнее.
"""


class Solution:
    def maxSlidingWindow(self, nums: list[int], k: int) -> list[int]:
        """
        Находит максимум в каждом скользящем окне размера k.
        Использует официальный max-heap из Python 3.14+ (heappush_max / heappop_max).
        """
        # Куча хранит кортежи (значение, индекс).
        # В отличие от старого подхода с отрицательными значениями,
        # мы храним исходные значения, так как heappush_max
        # автоматически поддерживает свойство max-heap:
        # элемент с наибольшим значением всегда находится на вершине (индекс 0).
        #
        # Пример: nums = [3, 1, 5]
        # В куче: [(5, 2), (3, 0), (1, 1)]
        # На вершине: (5, 2) → максимум = 5
        heap = []

        # Список для хранения результатов — максимумов каждого окна
        result = []

        # Проходим по всем элементам массива.
        # Индекс right одновременно является правой границей текущего окна.
        for right in range(len(nums)):
            # === ШАГ 1: Добавляем текущий элемент в кучу ===
            # heapq.heappush_max автоматически поддерживает свойство max-heap:
            # элемент с наибольшим значением окажется на вершине (индекс 0).
            #
            # Мы храним кортеж (значение, индекс), а не просто значение,
            # потому что нам нужно знать позицию элемента, чтобы определить,
            # вышел ли он за пределы скользящего окна.
            #
            # ВАЖНО: heapq сравнивает кортежи лексикографически — сначала по
            # первому элементу (значение), а при равенстве — по второму (индекс).
            # Это именно то, что нам нужно: максимум по значению, а при равенстве —
            # любой из них (индекс не важен для результата).
            heapq.heappush_max(heap, (nums[right], right))

            # === ШАГ 2: Удаляем "устаревшие" элементы с вершины кучи ===
            # Устаревший элемент — это тот, чей индекс вышел за пределы окна.
            #
            # Текущее окно: [right - k + 1, right]
            # Элемент с индексом heap[0][1] устарел, если heap[0][1] <= right - k
            # (то есть он находится левее левой границы окна).
            #
            # ВАЖНО: мы используем while, а не if, потому что на вершине кучи
            # может оказаться несколько устаревших элементов подряд.
            # Например, если максимальный элемент был в начале массива и
            # давно вышел из окна, а за ним шли другие устаревшие элементы.
            #
            # Также важно: мы удаляем элементы ТОЛЬКО С ВЕРШИНЫ кучи.
            # Если устаревший элемент находится в середине кучи — мы его не трогаем,
            # пока он не окажется на вершине. Это называется "ленивое удаление"
            # (lazy deletion) и является стандартным приёмом при работе с кучами.
            while heap[0][1] <= right - k:
                heapq.heappop_max(heap)  # Удаляем верхний (устаревший) элемент

            # === ШАГ 3: Записываем результат ===
            # Окно размера k полностью формируется, когда right достигает k-1.
            # До этого момента у нас меньше k элементов, и окно ещё не полное.
            #
            # Например, при k=3:
            # right=0 → окно [0,0] (1 элемент) — не полное
            # right=1 → окно [0,1] (2 элемента) — не полное
            # right=2 → окно [0,2] (3 элемента) — ПОЛНОЕ, записываем результат
            if right >= k - 1:
                # heap[0][0] — это значение максимума текущего окна.
                # В отличие от старого подхода с отрицательными значениями,
                # здесь нам НЕ нужно брать минус — значение уже правильное.
                result.append(heap[0][0])

        return result


def main():
    """Тест-кейсы для решения через Max-Heap (Python 3.14+)."""
    solution = Solution()

    print("=" * 60)
    print("ТЕСТИРОВАНИЕ РЕШЕНИЯ ЧЕРЕЗ MAX-HEAP (Python 3.14+)")
    print("=" * 60)

    # Тест 1: Стандартный случай из примера LeetCode
    nums = [1, 3, -1, -3, 5, 3, 6, 7]
    k = 3
    result = solution.maxSlidingWindow(nums, k)
    expected = [3, 3, 5, 5, 6, 7]
    print(f"\nТест 1: nums = {nums}, k = {k}")
    print(f"Результат: {result}")
    assert result == expected, (
        f"Тест 1 провален! Ожидалось {expected}, получено {result}"
    )
    print("✓ Пройден")

    # Тест 2: Окно размером 1 (минимальный случай)
    nums = [1]
    k = 1
    result = solution.maxSlidingWindow(nums, k)
    expected = [1]
    print(f"\nТест 2: nums = {nums}, k = {k} (окно = 1)")
    print(f"Результат: {result}")
    assert result == expected, f"Тест 2 провален!"
    print("✓ Пройден")

    # Тест 3: Окно равно длине массива (одно большое окно)
    nums = [1, 2, 3, 4, 5]
    k = 5
    result = solution.maxSlidingWindow(nums, k)
    expected = [5]
    print(f"\nТест 3: nums = {nums}, k = {k} (окно = длина массива)")
    print(f"Результат: {result}")
    assert result == expected, f"Тест 3 провален!"
    print("✓ Пройден")

    # Тест 4: Убывающая последовательность
    # Здесь максимум всегда первый элемент окна
    nums = [5, 4, 3, 2, 1]
    k = 3
    result = solution.maxSlidingWindow(nums, k)
    expected = [5, 4, 3]
    print(f"\nТест 4: nums = {nums}, k = {k} (убывающая)")
    print(f"Результат: {result}")
    assert result == expected, f"Тест 4 провален!"
    print("✓ Пройден")

    # Тест 5: Возрастающая последовательность
    # Здесь максимум всегда последний элемент окна
    nums = [1, 2, 3, 4, 5]
    k = 3
    result = solution.maxSlidingWindow(nums, k)
    expected = [3, 4, 5]
    print(f"\nТест 5: nums = {nums}, k = {k} (возрастающая)")
    print(f"Результат: {result}")
    assert result == expected, f"Тест 5 провален!"
    print("✓ Пройден")

    # Тест 6: Все элементы одинаковые
    nums = [7, 7, 7, 7, 7]
    k = 2
    result = solution.maxSlidingWindow(nums, k)
    expected = [7, 7, 7, 7]
    print(f"\nТест 6: nums = {nums}, k = {k} (все одинаковые)")
    print(f"Результат: {result}")
    assert result == expected, f"Тест 6 провален!"
    print("✓ Пройден")

    # Тест 7: Отрицательные числа
    # Проверяем, что с новыми методами нет проблем с отрицательными значениями
    nums = [-1, -3, -2, -5, -4]
    k = 2
    result = solution.maxSlidingWindow(nums, k)
    expected = [-1, -2, -2, -4]
    print(f"\nТест 7: nums = {nums}, k = {k} (отрицательные)")
    print(f"Результат: {result}")
    assert result == expected, f"Тест 7 провален!"
    print("✓ Пройден")

    # Тест 8: Окно размером 2 (минимальное нетривиальное)
    nums = [9, 11]
    k = 2
    result = solution.maxSlidingWindow(nums, k)
    expected = [11]
    print(f"\nТест 8: nums = {nums}, k = {k}")
    print(f"Результат: {result}")
    assert result == expected, f"Тест 8 провален!"
    print("✓ Пройден")

    # Тест 9: Большой массив (проверка производительности)
    import random

    random.seed(42)
    nums = [random.randint(-10000, 10000) for _ in range(10000)]
    k = 100
    result = solution.maxSlidingWindow(nums, k)
    # Проверяем корректность на нескольких случайных окнах
    for i in range(0, len(nums) - k + 1, 1000):
        expected_max = max(nums[i : i + k])
        assert result[i] == expected_max, f"Ошибка на позиции {i}!"
    print(f"\nТест 9: случайный массив из 10000 элементов, k = {k}")
    print(f"Результат: {len(result)} максимумов")
    print("✓ Пройден")

    print("\n" + "=" * 60)
    print("ВСЕ ТЕСТЫ ПРОЙДЕНЫ УСПЕШНО! ✓")
    print("=" * 60)


if __name__ == "__main__":
    main()
