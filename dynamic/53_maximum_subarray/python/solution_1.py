"""Ключевая идея (рекуррентность): best[i] — максимальная сумма подмассива, обязательно заканчивающегося в i.
Тогда:
best[i] = max(nums[i], best[i-1] + nums[i])
либо начинаем подмассив заново с nums[i] (если прежняя сумма отрицательна —
она лишь тянет вниз), либо продлеваем предыдущий. Ответ — максимум по всем best[i].
"""


class Solution:
    def maxSubArray(self, nums: list[int]) -> int:
        # current_sum — лучшая сумма подмассива, заканчивающегося ТЕКУЩИМ элементом
        # best_sum    — глобальный максимум среди всех таких сумм
        current_sum = best_sum = nums[0]

        for x in nums[1:]:
            # Продлевать прежний подмассив или стартовать заново с x?
            # Если current_sum < 0, прибавлять его бессмысленно — берём просто x
            current_sum = max(x, current_sum + x)

            # Текущий подмассив может оказаться лучшим за всю историю
            best_sum = max(best_sum, current_sum)

        return best_sum
