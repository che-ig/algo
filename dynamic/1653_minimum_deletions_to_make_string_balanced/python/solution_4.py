from functools import cache


class Solution:
    def minimumDeletions(self, s: str) -> int:
        return sol1(s)


def sol1(s):
    N = len(s)

    @cache
    def run(idx, seen):
        """
        Рекурсивная функция с мемоизацией.
        idx - текущая позиция в строке (0 .. N-1)
        seen - флаг: 0 если в префиксе ещё не было 'b',
                     1 если 'b' уже встречалась.
        Возвращает минимальное число удалений для подстроки s[idx:].
        """

        # Базовый случай: дошли до конца строки - удалять больше нечего
        if idx == N:
            return 0

        # Текущий символ
        ch = s[idx]

        # Случай 1: символ 'a' и мы ещё не видели 'b'
        # => такая 'a' не нарушает баланс (она идёт до всех 'b'),
        #    оставляем её, состояние seen остаётся 0
        if ch == "a" and not seen:
            return run(idx + 1, 0)

        # Случай 2: символ 'a', но 'b' уже была
        # => это создаёт пару b...a, нарушающую баланс
        #    Единственный выход — удалить эту 'a' (стоимость 1)
        #    и продолжить с seen=1
        if ch == "a" and seen:
            return 1 + run(idx + 1, 1)

        # Случай 3: символ 'b' и 'b' уже была
        # => это допустимо: все b идут после a,
        #    оставляем 'b' без удаления, seen остаётся 1
        if ch == "b" and seen:
            return run(idx + 1, 1)

        # Случай 4: символ 'b', но до этого 'b' не было (seen=0)
        # Здесь у нас есть два выбора:
        #   - удалить эту 'b' (стоимость 1), тогда seen остаётся 0
        #   - оставить 'b' (стоимость 0), тогда seen становится 1
        # Берём минимум из двух вариантов
        if ch == "b" and not seen:
            return min(
                1 + run(idx + 1, 0),  # удаляем текущую 'b'
                run(idx + 1, 1),  # оставляем, переходим в режим "видели b"
            )

        # Эта строка не должна выполняться (для всех случаев выше есть return)
        return 0

    # Запускаем с начала строки, флаг seen=0 (b не встречали)
    return run(0, 0)


def sol2(s):
    N = len(s)
    # dp[i][seen] - минимальное число удалений для подстроки s[i:]
    # seen = 0 - в суффиксе ещё не было 'b' (т.е. все символы справа - только 'a' или удалены)
    # seen = 1 - в суффиксе уже есть хотя бы одна 'b' (и все 'a' справа от неё уже удалены)
    dp = [[0] * 2 for _ in range(N + 1)]  # dp[N][*] = 0 (пустой суффикс)

    # Идём справа налево
    for i in range(N - 1, -1, -1):
        for seen in range(2):
            if s[i] == "a" and not seen:
                # Если текущий символ 'a' и справа нет 'b', его можно оставить
                dp[i][seen] = dp[i + 1][0]
            elif s[i] == "a" and seen:
                # Если справа уже есть 'b', то эта 'a' создаст пару b...a,
                # поэтому её нужно удалить (стоимость 1)
                dp[i][seen] = 1 + dp[i + 1][1]
            elif s[i] == "b" and seen:
                # Если справа уже есть 'b', то добавляем ещё одну 'b' — допустимо
                dp[i][seen] = dp[i + 1][1]
            else:  # s[i] == 'b' and not seen
                # Если это первая 'b' (справа её нет), то есть два варианта:
                # 1) удалить эту 'b' и остаться в состоянии seen=0
                # 2) оставить её, перейти в состояние seen=1
                dp[i][seen] = min(1 + dp[i + 1][0], dp[i + 1][1])

    # В начале (полная строка) seen=0, потому что справа нет 'b' (ещё не обработано)
    return dp[0][0]
