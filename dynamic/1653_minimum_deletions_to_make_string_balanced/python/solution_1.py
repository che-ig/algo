def minimumDeletions(s: str) -> int:
    """
    Находит минимальное количество удалений, чтобы сделать строку сбалансированной.

    Сбалансированная строка: все 'a' идут перед всеми 'b'.
    Примеры: "aaabbb", "aaaa", "bbbb", ""

    Алгоритм:
    1. Перебираем все возможные точки разделения строки
    2. Для каждой точки считаем:
       - Сколько 'b' нужно удалить слева (они нарушают порядок)
       - Сколько 'a' нужно удалить справа (они нарушают порядок)
    3. Возвращаем минимум по всем точкам
    """
    n = len(s)

    # Считаем общее количество 'a' в строке
    # Изначально точка разделения в начале (i=0),
    # значит все 'a' находятся справа и их нужно удалить
    a_count_right = s.count("a")

    # Количество 'b' слева от точки разделения (изначально 0)
    b_count_left = 0

    # Начальный ответ: удаляем все 'a' (точка разделения в начале)
    min_deletions = a_count_right

    # Перебираем все возможные точки разделения
    # i — индекс текущего символа, точка разделения проходит после него
    for i in range(n):
        if s[i] == "a":
            # Текущий символ 'a' переходит из правой части в левую
            # Значит, его больше не нужно удалять
            a_count_right -= 1
        else:  # s[i] == 'b'
            # Текущий символ 'b' находится в левой части
            # Его нужно будет удалить (так как слева должны быть только 'a')
            b_count_left += 1

        # Для текущей точки разделения:
        # - удаляем все 'b' слева (b_count_left)
        # - удаляем все 'a' справа (a_count_right)
        current_deletions = b_count_left + a_count_right

        # Обновляем минимум
        min_deletions = min(min_deletions, current_deletions)

    return min_deletions


# ===== АЛЬТЕРНАТИВНОЕ РЕШЕНИЕ ЧЕРЕЗ ДИНАМИЧЕСКОЕ ПРОГРАММИРОВАНИЕ =====
def minimumDeletions_dp(s: str) -> int:
    """
    Решение через ДП.

    dp[i] — минимальное количество удалений для префикса s[0..i-1],
    чтобы он был сбалансирован.

    При добавлении нового символа:
    - Если 'a': можем либо удалить его (+1), либо удалить все 'b' до него
    - Если 'b': просто добавляем в конец (ничего удалять не нужно)
    """
    # b_count — количество 'b', которые мы "оставили" (не удалили)
    b_count = 0

    # dp — минимальное количество удалений для текущего префикса
    dp = 0

    for char in s:
        if char == "b":
            # 'b' в конце — это хорошо, ничего удалять не нужно
            # Просто увеличиваем счётчик 'b'
            b_count += 1
        else:  # char == 'a'
            # 'a' после 'b' — нарушение баланса
            # Вариант 1: удалить текущий 'a' → dp + 1
            # Вариант 2: удалить все предыдущие 'b' → b_count
            # Выбираем минимум
            dp = min(dp + 1, b_count)

    return dp


