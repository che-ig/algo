class Solution:
    def minCostClimbingStairs(self, cost: list[int]) -> int:
        n = len(cost)

        # dp[i] — минимальная стоимость оказаться НА ступеньке i
        # (включая оплату cost[i]), придя сюда снизу
        dp = [0] * n

        # База: на ступеньки 0 и 1 можно просто стартовать,
        # заплатив их стоимость, — дешевле прийти сюда больше неоткуда
        dp[0] = cost[0]
        dp[1] = cost[1]

        # Собственно классическая рекуррентность:
        # на ступеньку i можно прийти только с i-1 или с i-2,
        # выбираем более дешёвый путь и сверху оплачиваем cost[i]
        for i in range(2, n):
            dp[i] = cost[i] + min(dp[i - 1], dp[i - 2])

        # Верх находится ЗА последней ступенькой (индекс n):
        # добраться туда одним шагом можно с n-1 или с n-2,
        # платить при этом больше не нужно — берём минимум из двух
        return min(dp[n - 1], dp[n - 2])
