class Solution:
    def climbStairs(self, n: int) -> int:
        # Базовые случаи, известные без вычислений:
        # n = 1 -> 1 способ:  [1]
        # n = 2 -> 2 способа: [1+1], [2]
        if n <= 2:
            return n

        # «Скользящее окно» из двух последних ответов:
        # prev хранит W(1) = 1, curr хранит W(2) = 2
        prev, curr = 1, 2

        # Двигаемся снизу вверх: вычисляем W(3), W(4), ..., W(n).
        # Каждый следующий ответ — сумма двух предыдущих,
        # т.к. последний шаг был либо 1 (пришли с n-1), либо 2 (пришли с n-2).
        for _ in range(3, n + 1):
            # Python сначала вычисляет правую часть со СТАРЫМИ значениями,
            # и только потом присваивает:
            #   новый prev = старый curr          (окно сдвигается вправо)
            #   новый curr = старый prev + старый curr  (новое W(i))
            # Временная переменная не нужна благодаря кортежному присваиванию.
            prev, curr = curr, prev + curr

        # Инвариант цикла: после итерации для i в curr лежит W(i).
        # Цикл закончился на i = n, значит curr == W(n) — ответ.
        return curr
