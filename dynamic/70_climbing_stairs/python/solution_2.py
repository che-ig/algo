class Solution:
    def climbStairs(self, n: int) -> int:
        # Кэш «ступенька k -> число способов W(k)»,
        # чтобы не пересчитывать одни и те же подзадачи.
        memo = {}

        def helper(k: int) -> int:
            # База рекурсии: для 1 и 2 ступенек ответ известен сразу.
            if k <= 2:
                return k

            # Подзадача уже решена — берём готовый ответ за O(1),
            # не запуская рекурсию повторно.
            if k in memo:
                return memo[k]

            # Иначе считаем через рекуррентность:
            # последний шаг 1 (helper(k-1)) или 2 (helper(k-2)),
            # и сохраняем результат в кэш для будущих вызовов.
            memo[k] = helper(k - 1) + helper(k - 2)
            return memo[k]

        # Стартуем с полной задачи; рекурсия сама «спустится» к базе,
        # а на обратном ходе заполнит кэш значениями W(3)..W(n).
        return helper(n)
