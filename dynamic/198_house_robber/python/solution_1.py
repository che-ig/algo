def rob(nums: list[int]) -> int:
    """
    Находит максимальную сумму, которую можно награбить,
    не затрагивая соседние дома.

    Основная идея: для каждого дома решаем, грабить его или нет.
    Если грабим текущий дом, то предыдущий грабить нельзя.
    """
    # Обработка граничных случаев
    if not nums:
        return 0  # Если домов нет, нечего грабить

    if len(nums) == 1:
        return nums[0]  # Если один дом, грабим его

    # dp[i] — максимальная сумма, которую можно получить
    # рассматривая дома от 0 до i включительно
    dp = [0] * len(nums)

    # ===== БАЗОВЫЕ СЛУЧАИ =====

    # Если есть только первый дом (индекс 0), грабим его
    dp[0] = nums[0]

    # Если есть два дома (индексы 0 и 1), выбираем тот, где больше денег
    # Нельзя грабить оба, так как они соседние
    dp[1] = max(nums[0], nums[1])

    # ===== ЗАПОЛНЕНИЕ ТАБЛИЦЫ ДИНАМИЧЕСКОГО ПРОГРАММИРОВАНИЯ =====

    # Начинаем с третьего дома (индекс 2), так как первые два уже обработали
    for i in range(2, len(nums)):
        # ===== ПРИНИМАЕМ РЕШЕНИЕ ДЛЯ ДОМА i =====

        # ВАРИАНТ 1: НЕ ГРАБИМ дом i
        # Если не грабим текущий дом, то максимальная сумма остаётся такой же,
        # как и для предыдущих домов (от 0 до i-1)
        skip_current = dp[i - 1]

        # ВАРИАНТ 2: ГРАБИМ дом i
        # Если грабим текущий дом, то:
        # - берём деньги из текущего дома: nums[i]
        # - добавляем максимальную сумму, которую получили до дома i-2
        #   (дом i-1 грабить нельзя, так как он соседний с i)
        rob_current = dp[i - 2] + nums[i]

        # ВЫБИРАЕМ ЛУЧШИЙ ВАРИАНТ
        # dp[i] = максимум из двух вариантов: грабить или не грабить
        dp[i] = max(skip_current, rob_current)

        # Для наглядности можно добавить отладочный вывод:
        # print(f"Дом {i} (деньги={nums[i]}): не грабить={skip_current}, "
        #       f"грабить={rob_current} → выбираем {dp[i]}")

    # Последний элемент dp содержит ответ для всех домов
    return dp[-1]


def rob_optimized(nums: list[int]) -> int:
    """
    Оптимизированная версия: храним только два последних значения.

    Заметим, что для вычисления dp[i] нам нужны только dp[i-1] и dp[i-2].
    Поэтому нет смысла хранить всю таблицу — достаточно двух переменных.
    """
    if not nums:
        return 0

    if len(nums) == 1:
        return nums[0]

    # prev2 хранит dp[i-2] — максимум для домов до предпредыдущего
    # Изначально это dp[0] — когда есть только первый дом
    prev2 = nums[0]

    # prev1 хранит dp[i-1] — максимум для домов до предыдущего
    # Изначально это dp[1] — когда есть два дома
    prev1 = max(nums[0], nums[1])

    # Начинаем с третьего дома (индекс 2)
    for i in range(2, len(nums)):
        # ===== ВЫЧИСЛЯЕМ МАКСИМУМ ДЛЯ ТЕКУЩЕГО ДОМА =====

        # Вариант 1: не грабим текущий дом → берём prev1
        # Вариант 2: грабим текущий дом → prev2 + nums[i]
        current_max = max(prev1, prev2 + nums[i])

        # ===== СДВИГАЕМ ОКНО =====
        # Теперь текущее значение становится "предыдущим" для следующей итерации

        # prev2 становится равным prev1 (сдвигаем на шаг вперёд)
        prev2 = prev1

        # prev1 становится равным current_max (сдвигаем на шаг вперёд)
        prev1 = current_max

        # После этого на следующей итерации:
        # - prev2 будет соответствовать dp[i-2]
        # - prev1 будет соответствовать dp[i-1]

    # После завершения цикла prev1 содержит ответ для всех домов
    return prev1


