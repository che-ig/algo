# вот где описана эта оптимизация http://e-maxx.ru/algo/longest_increasing_subseq_log
# Чтобы получить более быстрое решение задачи, построим другой вариант динамического программирования за O (n^2), а затем поймём, как можно этот вариант ускорить до O (n \log n).
#
# Динамика теперь будет такой: пусть d[i] (i = 0 \ldots n) — это число, на которое оканчивается возрастающая подпоследовательность длины i (а если таких чисел несколько — то наименьшее из них).
#
# Изначально мы полагаем d[0] = -\infty, а все остальные элементы d[i] = \infty.
#
# Считать эту динамику мы будем постепенно, обработав число a[0], затем a[1], и т.д.
class Solution:
    def lengthOfLIS(self, nums: list[int]) -> int:
        # tails[i] — наименьший последний элемент среди всех
        # возрастающих подпоследовательностей длины i+1
        # Этот массив ВСЕГДА отсортирован по возрастанию
        tails = []

        # Проходим по каждому числу в исходном массиве
        for num in nums:
            # ===== РУЧНОЙ БИНАРНЫЙ ПОИСК =====
            # Ищем позицию первого элемента в tails, который >= num
            # Это аналог bisect_left(tails, num)

            lo = 0  # левая граница поиска
            hi = len(tails)  # правая граница (не включительно)

            while lo < hi:
                # Находим середину
                mid = lo + (hi - lo) // 2

                if tails[mid] < num:
                    # Элемент в середине меньше num,
                    # значит искомая позиция правее
                    lo = mid + 1
                else:
                    # Элемент в середине >= num,
                    # значит искомая позиция здесь или левее
                    hi = mid

            # После цикла lo == hi — это и есть искомая позиция
            pos = lo

            # ===== ОБНОВЛЕНИЕ TAILS =====
            # Если позиция равна длине массива, значит num больше
            # ВСЕХ элементов в tails — добавляем в конец
            if pos == len(tails):
                tails.append(num)
            else:
                # Иначе заменяем элемент на позиции pos на num
                # (улучшаем tails для будущих расширений)
                tails[pos] = num

        # Длина tails — это длина наибольшей возрастающей подпоследовательности
        return len(tails)
