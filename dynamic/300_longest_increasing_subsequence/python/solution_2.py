from bisect import bisect_left


class Solution:
    def lengthOfLIS(self, nums: list[int]) -> int:
        # tails[i] — наименьший возможный последний элемент
        # среди всех возрастающих подпоследовательностей длины i+1
        # Этот массив всегда отсортирован по возрастанию!
        tails = []

        # Проходим по каждому числу в исходном массиве
        for num in nums:
            # Находим позицию, куда можно вставить текущее число
            # bisect_left возвращает индекс первого элемента >= num
            pos = bisect_left(tails, num)

            # Если позиция равна длине массива, значит num больше всех
            # элементов в tails — можем увеличить длину LIS
            if pos == len(tails):
                tails.append(num)
            else:
                # Иначе заменяем элемент на позиции pos на num.
                # Это не меняет длину LIS, но делает tails "лучше"
                # (меньшие элементы дают больше шансов для будущих расширений)
                tails[pos] = num

        # Длина массива tails — это и есть длина наибольшей LIS
        return len(tails)
