class Solution:
    def lengthOfLIS(self, nums: list[int]) -> int:
        # Если массив пустой, LIS = 0
        if not nums:
            return 0

        # dp[i] — длина наибольшей возрастающей подпоследовательности,
        # которая ЗАКАНЧИВАЕТСЯ элементом nums[i]
        # Изначально каждый элемент сам по себе образует LIS длины 1
        dp = [1] * len(nums)

        # Для каждого элемента массива (начиная со второго)
        for i in range(1, len(nums)):
            # Проверяем все предыдущие элементы
            for j in range(i):
                # Если предыдущий элемент меньше текущего (nums[j] < nums[i]),
                # значит мы можем продолжить подпоследовательность,
                # заканчивающуюся в j, добавив nums[i]
                if nums[j] < nums[i]:
                    # Обновляем dp[i]: берём максимум между текущим значением
                    # и длиной LIS до j плюс один (текущий элемент)
                    dp[i] = max(dp[i], dp[j] + 1)

        # Ответ — максимальное значение в dp, так как LIS может заканчиваться
        # в любом элементе массива, не обязательно в последнем
        return max(dp)
