def min_coins_with_trace(coins, S):
    # Бесконечность для обозначения невозможных сумм
    INF = float("inf")

    # dp[j] — минимальное количество монет для суммы j
    dp = [INF] * (S + 1)

    # prev[j] — какая монета была использована для суммы j
    # Нужно для восстановления ответа (какие именно монеты взяли)
    prev = [-1] * (S + 1)

    # Базовый случай: для суммы 0 нужно 0 монет
    dp[0] = 0

    # Для каждой суммы от 1 до S
    for j in range(1, S + 1):
        # Пробуем каждую монету
        for coin in coins:
            # Если монета не превышает текущую сумму
            # и использование этой монеты даёт лучшее решение
            if j >= coin and dp[j - coin] + 1 < dp[j]:
                # Обновляем минимальное количество монет
                dp[j] = dp[j - coin] + 1
                # Запоминаем, какую монету использовали для суммы j
                prev[j] = coin  # ← ВОТ ЭТА СТРОКА ПОДЧЁРКНУТА

    # Если сумма S недостижима
    if dp[S] == INF:
        return -1, []

    # Восстанавливаем, какие монеты были использованы
    result = []
    while S > 0:
        # Добавляем монету, которую использовали для суммы S
        result.append(prev[S])
        # Уменьшаем сумму на номинал этой монеты
        S -= prev[S]

    # Возвращаем минимальное количество монет и список монет
    return dp[-1], result
