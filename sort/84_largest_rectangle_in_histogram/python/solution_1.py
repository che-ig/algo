def largestRectangleArea(heights: list[int]) -> int:
    """
    Возвращает площадь наибольшего прямоугольника в гистограмме.
    :param heights: список высот столбцов (ширина каждого = 1)
    :return: максимальная площадь
    """
    n = len(heights)
    # Стек будет хранить индексы столбцов с возрастающими высотами.
    stack = []
    max_area = 0

    # Проходим по всем столбцам, добавляем фиктивный индекс n в конце,
    # чтобы обработать оставшиеся в стеке элементы.
    # Это удобно: при i = n мы считаем высоту = 0 (меньше любой),
    # что заставит вытолкнуть все оставшиеся индексы.
    for i in range(n + 1):
        # Текущая высота: для реальных индексов берём heights[i],
        # для фиктивного i == n используем 0, чтобы вытолкнуть всё.
        cur_h = heights[i] if i < n else 0

        # Пока стек не пуст и текущая высота меньше высоты вершины стека,
        # мы нашли правую границу для вершины.
        while stack and heights[stack[-1]] > cur_h:
            # Индекс столбца, для которого считаем площадь
            top = stack.pop()
            # Высота этого столбца
            h = heights[top]
            # Левая граница: если стек после извлечения не пуст,
            # то это индекс предыдущего элемента (он ниже или равен).
            # Если стек пуст, то левая граница = -1.
            left = stack[-1] if stack else -1
            # Правая граница: текущий индекс i (для реальных i)
            # или n (для фиктивного i == n, тогда i == n)
            right = i
            # Ширина = right - left - 1
            width = right - left - 1
            # Площадь
            area = h * width
            # Обновляем максимум
            if area > max_area:
                max_area = area

        # Помещаем текущий индекс в стек (кроме фиктивного, его не пушим)
        if i < n:
            stack.append(i)

    return max_area
