class Solution:
    def dailyTemperatures(self, temperatures: list[int]) -> list[int]:
        n = len(temperatures)

        # Массив ответов. По умолчанию все значения равны 0.
        # Это означает, что если для какого-то дня не найдётся
        # более тёплого дня в будущем, ответ останется 0.
        answer = [0] * n

        # Стек хранит ИНДЕКСЫ дней, для которых мы ещё не нашли
        # более тёплую температуру. Температуры по этим индексам
        # в стеке убывают (монотонно убывающий стек).
        stack = []

        # Проходим по каждому дню слева направо
        for i in range(n):
            # Пока стек не пуст и текущая температура ВЫШЕ,
            # чем температура на вершине стека
            while stack and temperatures[i] > temperatures[stack[-1]]:
                # Выталкиваем индекс дня, для которого нашли ответ
                prev_day = stack.pop()

                # Количество дней ожидания = текущий индекс - индекс того дня
                answer[prev_day] = i - prev_day

            # Добавляем текущий день в стек.
            # Теперь температуры в стеке снова убывают.
            stack.append(i)

        return answer


# --- Проверка на примерах ---
if __name__ == "__main__":
    sol = Solution()

    print(sol.dailyTemperatures([73, 74, 75, 71, 69, 72, 76, 73]))  # [1,1,4,2,1,1,0,0]
    print(sol.dailyTemperatures([30, 40, 50, 60]))  # [1,1,1,0]
    print(sol.dailyTemperatures([30, 60, 90]))  # [1,1,0]
