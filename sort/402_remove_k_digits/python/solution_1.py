def removeKdigits(num: str, k: int) -> str:
    """
    Удаляет k цифр из числа num так, чтобы получить минимальное возможное число.

    Алгоритм:
    1. Жадно удаляем цифры, которые больше следующей (через монотонный стек).
    2. Если после прохода остались удаления — убираем с конца.
    3. Убираем ведущие нули.

    Сложность: O(n) по времени и памяти.
    """
    # Стек будет хранить цифры в монотонно возрастающем порядке
    stack = []

    # Проходим по всем цифрам числа
    for digit in num:
        # Пока можем удалять (k > 0), стек не пуст,
        # и текущая цифра МЕНЬШЕ вершины стека —
        # удаляем вершину: она «портит» число, стоя перед меньшей цифрой
        while k > 0 and stack and digit < stack[-1]:
            stack.pop()
            k -= 1

        # Кладём текущую цифру в стек
        stack.append(digit)

    # Если после прохода k ещё > 0 — удаляем k цифр с конца.
    # Это нужно, когда массив был неубывающим (например, "12345"),
    # и мы не смогли ничего удалить во время прохода.
    # В таком случае самые большие цифры стоят в конце — их и убираем.
    if k > 0:
        stack = stack[:-k]

    # Собираем результат из стека
    result = "".join(stack)

    # Убираем ведущие нули (lstrip('0') удаляет все нули слева)
    result = result.lstrip("0")

    # Если после удаления нулей строка пустая — значит, число было 0
    return result if result else "0"


# ===== Проверка на примерах =====
if __name__ == "__main__":
    # Пример 1
    print(removeKdigits("1432219", 3))  # Ожидаем: "1219"

    # Пример 2
    print(removeKdigits("10200", 1))  # Ожидаем: "200"

    # Пример 3
    print(removeKdigits("10", 2))  # Ожидаем: "0"

    # Дополнительные тесты
    print(removeKdigits("12345", 2))  # Ожидаем: "123" (удаляем с конца)
    print(removeKdigits("10001", 4))  # Ожидаем: "0" (остаётся только "0")
