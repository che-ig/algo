def nextGreaterElement(nums1: list[int], nums2: list[int]) -> list[int]:
    """
    Для каждого элемента nums1 находим следующий больший элемент в nums2 справа.

    Алгоритм:
    1. Проходим по nums2, поддерживая монотонный убывающий стек.
    2. Когда текущий элемент больше вершины стека — это и есть "следующий больший"
       для вершины. Сохраняем пару в словарь.
    3. Для каждого элемента nums1 берём ответ из словаря (или -1, если его нет).

    Сложность: O(len(nums1) + len(nums2)) по времени, O(len(nums2)) по памяти.
    """

    # Словарь: элемент -> его следующий больший элемент в nums2
    next_greater = {}

    # Монотонный стек: храним элементы nums2 в убывающем порядке
    # (снизу стека — большие, сверху — меньшие)
    stack = []

    # Проходим по nums2 слева направо
    for num in nums2:
        # Пока стек не пуст и текущий элемент больше вершины стека:
        # значит, для вершины стека мы нашли следующий больший элемент
        while stack and stack[-1] < num:
            smaller = stack.pop()  # элемент, для которого нашли ответ
            next_greater[smaller] = num  # сохраняем в словарь

        # Кладём текущий элемент в стек — он ждёт своего "следующего большего"
        stack.append(num)

    # Формируем ответ для nums1:
    # если для элемента есть запись в словаре — берём её, иначе -1
    ans = [next_greater.get(num, -1) for num in nums1]

    return ans


# ===== Проверка на примерах из условия =====
if __name__ == "__main__":
    # Пример 1
    nums1 = [4, 1, 2]
    nums2 = [1, 3, 4, 2]
    print(nextGreaterElement(nums1, nums2))  # Ожидаем: [-1, 3, -1]

    # Пример 2
    nums1 = [2, 4]
    nums2 = [1, 2, 3, 4]
    print(nextGreaterElement(nums1, nums2))  # Ожидаем: [3, -1]
