class Solution:
    def isValid(self, s: str) -> bool:
        # Стек для хранения открывающих скобок
        stack = []

        # Словарь соответствий: закрывающая скобка → открывающая скобка
        # Позволяет быстро проверить, какая открывающая скобка должна быть на вершине
        matching = {")": "(", "}": "{", "]": "["}

        # Множество открывающих скобок для быстрой проверки
        open_brackets = set("({[")

        # Проходим по каждому символу в строке
        for char in s:
            if char in open_brackets:
                # Если это открывающая скобка — кладём её в стек
                stack.append(char)
            else:
                # Это закрывающая скобка
                # Проверяем два условия:
                # 1. Стек не пуст (есть ли открывающая скобка для пары)
                # 2. Верхний элемент стека — соответствующая открывающая скобка
                if not stack or stack[-1] != matching[char]:
                    return False
                # Если всё ок — снимаем открывающую скобку со стека
                stack.pop()

        # После обработки всей строки стек должен быть пуст.
        # Если в нём что-то осталось — есть незакрытые открывающие скобки.
        return len(stack) == 0


# --- Проверка на примерах ---
if __name__ == "__main__":
    sol = Solution()

    print(sol.isValid("()"))  # True
    print(sol.isValid("()[]{}"))  # True
    print(sol.isValid("(]"))  # False
    print(sol.isValid("([])"))  # True
    print(sol.isValid("([)]"))  # False
    print(sol.isValid("("))  # False (незакрытая скобка)
