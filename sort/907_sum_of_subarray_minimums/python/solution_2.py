class Solution:
    def sumSubarrayMins(self, arr: list[int]) -> int:
        MOD = 10**9 + 7
        n = len(arr)

        # dp[i] — сумма минимумов всех подмассивов, заканчивающихся в позиции i
        dp = [0] * n

        # Монотонный стек: хранит индексы элементов в порядке возрастания их значений.
        # Помогает быстро найти ближайший меньший элемент слева.
        stack = []

        for i in range(n):
            # Удаляем из стека все элементы, которые >= текущего,
            # так как они не могут быть минимумом для подмассивов,
            # содержащих arr[i]
            while stack and arr[stack[-1]] >= arr[i]:
                stack.pop()

            if stack:
                # j — индекс ближайшего элемента слева, строго меньшего arr[i]
                j = stack[-1]
                # Для (i - j) подмассивов минимум — сам arr[i],
                # для остальных — минимум совпадает с dp[j]
                dp[i] = dp[j] + arr[i] * (i - j)
            else:
                # Слева нет элемента меньше текущего,
                # значит arr[i] — минимум для всех (i + 1) подмассивов
                dp[i] = arr[i] * (i + 1)

            # Кладём текущий индекс в стек
            stack.append(i)

        # Ответ — сумма всех dp[i] по модулю 10^9 + 7
        return sum(dp) % MOD
