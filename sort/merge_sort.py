# ==========================================
if __name__ == "__main__":
    # Исходный неотсортированный массив
    my_list = [38, 27, 43, 3, 9, 82, 10, 19, -5, 0]
    print(f"Исходный массив: {my_list}")

    # Вызываем сортировку
    sorted_list = merge_sort(my_list)

    print(f"Отсортированный массив: {sorted_list}")
