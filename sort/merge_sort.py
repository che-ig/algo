def merge_sort(arr: list) -> list:
    """
    Рекурсивная функция сортировки слиянием.
    Делит массив на две половины, сортирует их и возвращает результат слияния.
    """
    # Базовый случай рекурсии: массив из 0 или 1 элемента уже отсортирован
    if len(arr) <= 1:
        return arr

    # Шаг 1: РАЗДЕЛЯЙ (Divide)
    # Находим индекс середины массива
    mid = len(arr) // 2

    # Делим массив на левую и правую половины
    left_half = arr[:mid]
    right_half = arr[mid:]

    # Шаг 2: ВЛАСТВУЙ (Conquer)
    # Рекурсивно сортируем обе половины
    sorted_left = merge_sort(left_half)
    sorted_right = merge_sort(right_half)

    # Шаг 3: КОМБИНИРУЙ (Combine)
    # Сливаем две отсортированные половины в один массив
    return merge(sorted_left, sorted_right)


def merge(left: list, right: list) -> list:
    """
    Вспомогательная функция для слияния двух отсортированных массивов в один.
    """
    merged = []  # Список для хранения итогового отсортированного массива
    i = 0  # Указатель для массива left
    j = 0  # Указатель для массива right

    # Сравниваем элементы из обоих массивов и добавляем меньший в результат
    while i < len(left) and j < len(right):
        if left[i] <= right[j]:
            merged.append(left[i])
            i += 1  # Сдвигаем указатель левого массива
        else:
            merged.append(right[j])
            j += 1  # Сдвигаем указатель правого массива

    # Если в левом массиве остались элементы (они все больше тех, что уже добавлены),
    # просто добавляем их в конец результирующего массива
    merged.extend(left[i:])

    # Аналогично добавляем остатки из правого массива, если они есть
    merged.extend(right[j:])

    return merged


