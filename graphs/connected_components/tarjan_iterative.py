def tarjan_iterative(graph):
    """
    Итеративная версия алгоритма Тарьяна для поиска SCC.

    Эмулирует рекурсивный DFS через явный стек вызовов,
    чтобы избежать RecursionError на больших графах.

    Args:
        graph: dict, список смежности ориентированного графа.
               Пример: {'A': ['B', 'C'], 'B': ['A'], 'C': []}

    Returns:
        list of lists: каждая компонента — список вершин SCC.
    """

    # -------------------------------------------------------
    # Счётчик "времени" посещения вершин.
    # Каждой новой вершине присваиваем уникальный номер.
    # Используем обычную переменную (не список), потому что
    # она не нужна внутри вложенной функции.
    # -------------------------------------------------------
    index_counter = 0

    # -------------------------------------------------------
    # Стек для SCC. Хранит вершины в порядке их посещения.
    # Когда находим корень SCC — выгребаем из него все вершины
    # до этого корня включительно.
    # -------------------------------------------------------
    stack = []

    # -------------------------------------------------------
    # lowlink[v] — минимальный index, достижимый из поддерева v
    # через back-edges (рёбра в вершины, которые сейчас в стеке).
    # Если lowlink[v] == index[v], то v — корень SCC.
    # -------------------------------------------------------
    lowlink = {}

    # -------------------------------------------------------
    # index[v] — "время" первого посещения вершины v.
    # Также служит маркером: если v в index — значит, посещена.
    # -------------------------------------------------------
    index = {}

    # -------------------------------------------------------
    # Множество вершин, которые сейчас находятся в стеке SCC.
    # Нужно, чтобы отличать back-edge (ребро в "серую" вершину)
    # от cross-edge (ребро в уже полностью обработанную вершину).
    # -------------------------------------------------------
    on_stack = set()

    # -------------------------------------------------------
    # Результат: список найденных SCC.
    # -------------------------------------------------------
    sccs = []

    # -------------------------------------------------------
    # СТЕК ВЫЗОВОВ — ключевая структура итеративной версии.
    # Каждый кадр — это кортеж (вершина, итератор по соседям).
    #
    # Зачем итератор? Потому что после "возврата" из рекурсии
    # мы должны продолжить обход соседей с того места,
    # где остановились. Итератор хранит это состояние.
    #
    # Аналогия с рекурсией:
    #   def dfs(v):
    #       for w in graph[v]:      ← итератор по соседям
    #           if w не посещён:
    #               dfs(w)          ← кладём новый кадр в стек
    #               # после возврата продолжаем цикл for
    # -------------------------------------------------------
    call_stack = []

    # -------------------------------------------------------
    # Внешний цикл: запускаем DFS от каждой непосещённой вершины.
    # Это нужно для обработки несвязных графов.
    # -------------------------------------------------------
    for start in graph:
        if start in index:
            # Вершина уже была посещена в предыдущем DFS — пропускаем
            continue

        # -------------------------------------------------------
        # Инициализация стартовой вершины.
        # Это аналог первых строк рекурсивной strongconnect(v).
        # -------------------------------------------------------
        index[start] = index_counter
        lowlink[start] = index_counter
        index_counter += 1

        # Кладём вершину в стек SCC и помечаем как "на стеке"
        stack.append(start)
        on_stack.add(start)

        # Кладём первый кадр в стек вызовов:
        # - start: текущая вершина
        # - iter(...): итератор по её соседям
        call_stack.append((start, iter(graph.get(start, []))))

        # -------------------------------------------------------
        # Основной цикл: пока стек вызовов не пуст,
        # мы "в процессе DFS".
        # -------------------------------------------------------
        while call_stack:
            # Смотрим на верхний кадр стека, НЕ извлекая его.
            # v — текущая вершина, neighbors — итератор по её соседям.
            v, neighbors = call_stack[-1]

            try:
                # Пытаемся получить следующего соседа.
                # Если соседи кончились — будет StopIteration.
                w = next(neighbors)

                if w not in index:
                    # -------------------------------------------------------
                    # Случай 1: сосед w ещё не посещён.
                    # Это аналог рекурсивного вызова strongconnect(w).
                    # -------------------------------------------------------

                    # Инициализируем w так же, как стартовую вершину
                    index[w] = index_counter
                    lowlink[w] = index_counter
                    index_counter += 1

                    # Кладём w в стек SCC
                    stack.append(w)
                    on_stack.add(w)

                    # Кладём НОВЫЙ кадр в стек вызовов.
                    # Теперь на вершине стека — w, и мы будем
                    # обходить его соседей.
                    call_stack.append((w, iter(graph.get(w, []))))

                elif w in on_stack:
                    # -------------------------------------------------------
                    # Случай 2: сосед w уже посещён И находится в стеке.
                    # Это back-edge — ребро в "серую" вершину.
                    # Обновляем lowlink[v] через index[w] (не lowlink!).
                    #
                    # Почему через index, а не lowlink?
                    # Потому что lowlink[w] может ещё измениться,
                    # а index[w] — фиксированное значение.
                    # -------------------------------------------------------
                    lowlink[v] = min(lowlink[v], index[w])

                # Если w посещён, но НЕ в on_stack — это cross-edge
                # (ребро в "чёрную" вершину). Игнорируем.

            except StopIteration:
                # -------------------------------------------------------
                # Все соседи v обработаны.
                # Это аналог "возврата" из рекурсивного вызова.
                # -------------------------------------------------------

                # Убираем текущий кадр из стека вызовов
                call_stack.pop()

                # -------------------------------------------------------
                # Обновляем lowlink родителя.
                # В рекурсивной версии это происходит автоматически:
                #   strongconnect(w)
                #   lowlink[v] = min(lowlink[v], lowlink[w])  ← здесь
                #
                # В итеративной версии мы делаем это вручную:
                # если стек вызовов не пуст, значит у v есть родитель.
                # -------------------------------------------------------
                if call_stack:
                    parent = call_stack[-1][0]
                    lowlink[parent] = min(lowlink[parent], lowlink[v])

                # -------------------------------------------------------
                # Проверяем, является ли v корнем SCC.
                # Если lowlink[v] == index[v], то из поддерева v
                # нельзя добраться до более ранних вершин —
                # значит, v начинает новую SCC.
                # -------------------------------------------------------
                if lowlink[v] == index[v]:
                    # Выгребаем SCC из стека
                    scc = []
                    while True:
                        w = stack.pop()
                        on_stack.remove(w)
                        scc.append(w)
                        if w == v:
                            # Дошли до корня — SCC собрана
                            break
                    sccs.append(scc)

    return sccs


def normalize(sccs):
    """Приводим SCC к сравнимому виду."""
    return sorted([sorted(scc) for scc in sccs])


