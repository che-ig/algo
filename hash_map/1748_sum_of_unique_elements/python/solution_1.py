from collections import Counter


class Solution:
    def sumOfUnique(self, nums: list[int]) -> int:
        """
        Возвращает сумму элементов, встречающихся в массиве ровно один раз.

        Используем Counter для подсчёта частот, затем суммируем
        только те элементы, у которых частота равна 1.
        """
        # Counter автоматически считает частоты каждого элемента.
        # Например: Counter([1,2,3,2]) → {1: 1, 2: 2, 3: 1}
        count = Counter(nums)

        # Суммируем только те элементы, которые встречаются ровно один раз.
        # Генераторное выражение перебирает пары (элемент, частота)
        # и включает элемент в сумму только если его частота == 1.
        return sum(num for num, freq in count.items() if freq == 1)
