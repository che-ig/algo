class Solution:
    def twoSum(self, nums: list[int], target: int) -> list[int]:
        """
        Возвращает индексы двух чисел, сумма которых равна target.

        Используем хеш-таблицу (словарь) для хранения уже увиденных чисел
        и их индексов. Для каждого числа проверяем, есть ли в словаре
        его дополнение (target - num).
        """
        # Словарь для хранения уже увиденных чисел и их индексов.
        # Ключ — число, значение — его индекс в массиве.
        # Например, после обработки nums[0]=2: seen = {2: 0}
        seen = {}

        # Проходим по массиву с индексами
        for i, num in enumerate(nums):
            # Вычисляем дополнение — число, которое в паре с num даст target.
            # Если num + complement = target, то complement = target - num.
            #
            # Пример: target = 9, num = 7 → complement = 9 - 7 = 2
            complement = target - num

            # Проверяем, есть ли дополнение среди уже увиденных чисел.
            # Поиск в словаре работает за O(1) в среднем (хеш-таблица).
            if complement in seen:
                # Нашли пару! Возвращаем индекс дополнения и текущий индекс.
                # seen[complement] — это индекс числа, которое мы видели раньше.
                # i — индекс текущего числа.
                return [seen[complement], i]

            # Если дополнения нет в словаре, добавляем текущее число и его индекс.
            # Это нужно для будущих итераций, чтобы другие числа могли найти
            # текущее как своё дополнение.
            seen[num] = i

        # По условию задачи решение всегда существует,
        # поэтому сюда мы никогда не дойдём.
        # Но формально нужно вернуть что-то:
        return []
