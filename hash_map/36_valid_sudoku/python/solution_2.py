def isValidSudoku(board: list[list[str]]) -> bool:
    """
    Проверяет, валидна ли доска судоку.

    Алгоритм:
    1. Создаём три набора множеств:
       - rows[i] — множество цифр в строке i
       - cols[j] — множество цифр в столбце j
       - boxes[(i//3, j//3)] — множество цифр в блоке 3x3
    2. Проходим по всем клеткам доски.
    3. Для каждой заполненной клетки проверяем:
       - нет ли цифры в множестве строки
       - нет ли цифры в множестве столбца
       - нет ли цифры в множестве блока
    4. Если цифра уже есть — возвращаем False.
    5. Иначе добавляем цифру во все три множества.

    Сложность: O(81) = O(1) по времени и памяти (фиксированный размер доски 9x9).
    """
    # Множества для строк: rows[i] хранит цифры строки i
    rows = [set() for _ in range(9)]

    # Множества для столбцов: cols[j] хранит цифры столбца j
    cols = [set() for _ in range(9)]

    # Множества для блоков 3x3: boxes[(i//3, j//3)] хранит цифры блока
    boxes = [set() for _ in range(9)]

    # Проходим по всем клеткам доски
    for i in range(9):
        for j in range(9):
            cell = board[i][j]

            # Пропускаем пустые клетки
            if cell == ".":
                continue

            # Вычисляем индекс блока 3x3
            # Блоки нумеруются от 0 до 8:
            # 0 1 2
            # 3 4 5
            # 6 7 8
            box_idx = (i // 3) * 3 + (j // 3)

            # Проверяем, не нарушает ли цифра правила
            if cell in rows[i] or cell in cols[j] or cell in boxes[box_idx]:
                return False

            # Добавляем цифру во все три множества
            rows[i].add(cell)
            cols[j].add(cell)
            boxes[box_idx].add(cell)

    # Если прошли всю доску без нарушений — она валидна
    return True


# ===== Альтернативная реализация с кортежами для блоков =====
def isValidSudoku_v2(board: list[list[str]]) -> bool:
    """
    Альтернативная версия: используем кортеж (i//3, j//3) как ключ блока.
    """
    rows = [set() for _ in range(9)]
    cols = [set() for _ in range(9)]
    boxes = {}  # Словарь: (i//3, j//3) -> set

    for i in range(9):
        for j in range(9):
            cell = board[i][j]

            if cell == ".":
                continue

            box_key = (i // 3, j // 3)

            if cell in rows[i] or cell in cols[j] or cell in boxes.get(box_key, set()):
                return False

            rows[i].add(cell)
            cols[j].add(cell)
            if box_key not in boxes:
                boxes[box_key] = set()
            boxes[box_key].add(cell)

    return True


