class Solution:
    def countKDifference(self, nums: list[int], k: int) -> int:
        """
        Возвращает количество пар с абсолютной разницей k.
        Использует массив частот, так как значения nums[i] <= 100.
        """
        # Создаём массив частот для чисел от 0 до 100.
        count = [0] * 101

        # Считаем, сколько раз встречается каждое число
        for num in nums:
            count[num] += 1

        pairs = 0

        # Проходим по всем возможным значениям x.
        # Нам нужно, чтобы x + k <= 100, поэтому x <= 100 - k.
        for x in range(1, 101 - k):
            # Если x встречается A раз, а x+k встречается B раз,
            # они образуют A * B пар.
            pairs += count[x] * count[x + k]

        return pairs
