class Solution:
    def isPathCrossing(self, path: str) -> bool:
        """
        Проверяет, пересекает ли путь сам себя.

        Симулируем движение по плоскости, начиная с (0, 0).
        Храним все посещённые точки в set.
        Если текущая точка уже есть в set — путь пересекается.
        """
        # Начальная позиция — начало координат
        x, y = 0, 0

        # Множество посещённых точек.
        # Используем кортежи (x, y) как элементы set, так как кортежи хешируемы.
        # Добавляем начальную точку (0, 0) — мы уже её посетили.
        visited = {(0, 0)}

        # Словарь направлений: каждая буква соответствует изменению координат.
        # 'N' → y увеличивается на 1 (движение вверх)
        # 'S' → y уменьшается на 1 (движение вниз)
        # 'E' → x увеличивается на 1 (движение вправо)
        # 'W' → x уменьшается на 1 (движение влево)
        directions = {"N": (0, 1), "S": (0, -1), "E": (1, 0), "W": (-1, 0)}

        # Проходим по каждому шагу пути
        for step in path:
            # Получаем изменение координат для текущего направления
            dx, dy = directions[step]

            # Обновляем текущую позицию
            x += dx
            y += dy

            # Проверяем, были ли мы уже в этой точке
            if (x, y) in visited:
                # Точка уже посещена — путь пересекается
                return True

            # Добавляем новую точку в множество посещённых
            visited.add((x, y))

        # Если прошли весь путь без повторных посещений — пересечения нет
        return False
