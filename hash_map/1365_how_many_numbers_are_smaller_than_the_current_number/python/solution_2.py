class Solution:
    def smallerNumbersThanCurrent(self, nums: list[int]) -> list[int]:
        """
        Возвращает массив, где для каждого nums[i] указано количество чисел,
        строго меньших его.

        Используем сортировку подсчётом (Counting Sort) и префиксные суммы.
        Сложность: O(N + K), где K = 101 — диапазон значений.
        """
        # Шаг 1: Считаем частоты каждого числа.
        # count[v] = сколько раз число v встречается в nums.
        count = [0] * 101
        for num in nums:
            count[num] += 1

        # Шаг 2: Преобразуем массив частот в массив префиксных сумм.
        # После этого count[i] будет хранить количество чисел,
        # которые МЕНЬШЕ ИЛИ РАВНЫ i.
        #
        # Пример: если в массиве [0, 1, 2, 2, 3]
        # Исходные частоты: count[0]=0, count[1]=1, count[2]=2, count[3]=1
        # После префиксных сумм:
        #   count[0] = 0  (чисел <= 0: ноль)
        #   count[1] = 0 + 1 = 1  (чисел <= 1: один)
        #   count[2] = 1 + 2 = 3  (чисел <= 2: три)
        #   count[3] = 3 + 1 = 4  (чисел <= 3: четыре)
        for i in range(1, 101):
            count[i] += count[i - 1]

        # Шаг 3: Формируем ответ.
        # Количество чисел, СТРОГО МЕНЬШИХ num, равно count[num - 1]
        # (количество чисел <= num-1, то есть < num).
        # Для num = 0 ответ всегда 0 (меньше нуля чисел нет).
        return [count[num - 1] if num > 0 else 0 for num in nums]
