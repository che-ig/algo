from collections import Counter


class Solution:
    def uniqueOccurrences(self, arr: list[int]) -> bool:
        """
        Проверяет, все ли частоты вхождений элементов в массиве уникальны.

        Алгоритм:
        1. Считаем частоты каждого элемента через Counter
        2. Проверяем, что все частоты уникальны через set
        """
        # Считаем частоты каждого элемента.
        # Counter([1,2,2,1,1,3]) → {1: 3, 2: 2, 3: 1}
        count = Counter(arr)

        # Извлекаем все частоты (значения словаря).
        # Для примера выше: [3, 2, 1]
        frequencies = count.values()

        # Если количество уникальных частот равно общему количеству частот,
        # значит все частоты уникальны.
        # set() удаляет дубликаты, поэтому len(set(frequencies)) покажет
        # количество уникальных частот.
        return len(set(frequencies)) == len(frequencies)
