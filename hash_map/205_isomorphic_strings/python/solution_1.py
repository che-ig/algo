def isIsomorphic(s: str, t: str) -> bool:
    """
    Проверяет, являются ли строки s и t изоморфными.

    Алгоритм:
    1. Используем словарь для хранения соответствия char_s -> char_t.
    2. Используем множество для хранения уже использованных символов из t.
       Это гарантирует, что два разных символа из s не сопоставятся одному символу из t.
    3. Проходим по строкам одновременно (zip).

    Сложность: O(n) по времени, O(1) по памяти (т.к. алфавит ASCII ограничен 256 символами).
    """
    # Если длины разные, изоморфизм невозможен (хотя по условию они равны)
    if len(s) != len(t):
        return False

    # Словарь для маппинга: символ из s -> символ из t
    char_map = {}

    # Множество для отслеживания символов из t, которые уже кем-то заняты
    used_t_chars = set()

    # Проходим по обеим строкам одновременно
    for char_s, char_t in zip(s, t):
        # Если символ из s уже имеет сопоставление
        if char_s in char_map:
            # Проверяем, совпадает ли оно с текущим символом из t
            if char_map[char_s] != char_t:
                return False
        else:
            # Если символ из s новый, проверяем, не занят ли уже символ из t
            if char_t in used_t_chars:
                return False

            # Создаем новое сопоставление
            char_map[char_s] = char_t
            used_t_chars.add(char_t)

    return True
