class Solution:
    def findDifference(self, nums1: list[int], nums2: list[int]) -> list[list[int]]:
        """
        Возвращает два списка:
        - answer[0]: уникальные элементы nums1, которых нет в nums2
        - answer[1]: уникальные элементы nums2, которых нет в nums1

        Использует операции над множествами для эффективного поиска различий.
        """
        # Превращаем оба массива в множества.
        # Это автоматически удаляет дубликаты и позволяет выполнять
        # операции разности за O(N) вместо O(N²).
        #
        # Пример: nums1 = [1, 2, 3, 3] → set1 = {1, 2, 3}
        set1 = set(nums1)
        set2 = set(nums2)

        # Операция разности множеств: set1 - set2
        # Возвращает все элементы из set1, которых нет в set2.
        # Результат — тоже множество, поэтому преобразуем обратно в список.
        #
        # Пример: {1, 2, 3} - {2, 4, 6} = {1, 3}
        diff1 = list(set1 - set2)

        # Аналогично для set2 - set1
        # Пример: {2, 4, 6} - {1, 2, 3} = {4, 6}
        diff2 = list(set2 - set1)

        # Возвращаем результат в требуемом формате
        return [diff1, diff2]
