def isReflected(points: list[list[int]]) -> bool:
    """
    Проверяет, существует ли вертикальная линия, относительно которой
    множество точек симметрично.

    Алгоритм:
    1. Находим min_x и max_x — они определяют единственную возможную линию симметрии.
    2. Линия симметрии: x = (min_x + max_x) / 2.
    3. Для каждой точки (x, y) проверяем, есть ли её отражение (min_x + max_x - x, y).

    Сложность: O(n) по времени, O(n) по памяти.
    """
    if not points:
        return True

    # Находим минимальную и максимальную координату X
    # Это определит единственную возможную линию симметрии
    min_x = min(p[0] for p in points)
    max_x = max(p[0] for p in points)

    # Сумма min_x + max_x — это удвоенная координата линии симметрии.
    # Используем сумму, чтобы избежать деления и проблем с float.
    # Если линия симметрии x = mid, то mid = (min_x + max_x) / 2,
    # а отражение точки x будет: 2 * mid - x = min_x + max_x - x
    sum_x = min_x + max_x

    # Помещаем все точки в множество для O(1) поиска.
    # Также это автоматически убирает дубликаты (они не влияют на симметрию).
    point_set = set()
    for x, y in points:
        point_set.add((x, y))

    # Проверяем каждую точку: существует ли её отражение?
    for x, y in point_set:
        # Координата X отражённой точки
        reflected_x = sum_x - x

        # Если отражённой точки нет в множестве — симметрии нет
        if (reflected_x, y) not in point_set:
            return False

    # Все точки имеют свои отражения — симметрия есть
    return True


# ===== Проверка на примерах =====
if __name__ == "__main__":
    # Пример 1: точки симметричны относительно x = 0
    points1 = [[1, 1], [-1, 1]]
    print(isReflected(points1))  # Ожидаем: True

    # Пример 2: точки не симметричны ни относительно какой вертикальной линии
    points2 = [[1, 1], [-1, -1]]
    print(isReflected(points2))  # Ожидаем: False

    # Дополнительные тесты
    # Точки на одной вертикальной линии — всегда симметричны
    print(isReflected([[1, 1], [1, 2], [1, 3]]))  # True

    # С дубликатами
    print(isReflected([[1, 1], [1, 1], [-1, 1], [-1, 1]]))  # True

    # Одна точка — всегда симметрична
    print(isReflected([[5, 5]]))  # True
