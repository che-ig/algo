"""
Алгоритм работает следующим образом:

    Сортируем массив по возрастанию. Это позволит нам легко пропускать дубликаты и управлять суммой (увеличивать или уменьшать её).
    Проходим по массиву, фиксируя первый элемент тройки (nums[i]).
    Для оставшейся части массива используем два указателя (left и right), чтобы найти два других элемента, которые в сумме с nums[i] дадут 0.
    Если сумма меньше 0, сдвигаем левый указатель вправо (чтобы увеличить сумму). Если больше 0 — сдвигаем правый указатель влево (чтобы уменьшить сумму). Если равна 0 — добавляем тройку в результат и сдвигаем оба указателя, пропуская дубликаты.
"""

## 2. Оптимизация `if nums[i] > 0: break`

# Массив **отсортирован по возрастанию**. Это означает:
# nums[0] ≤ nums[1] ≤ nums[2] ≤ ... ≤ nums[n-1]
#
# Если мы дошли до элемента `nums[i] > 0`, то **все последующие элементы тоже больше 0**:
# nums[i] > 0, nums[i+1] > 0, nums[i+2] > 0, ...
#
# Сумма **трех положительных чисел** никогда не может быть равна `0`:
# nums[i] + nums[left] + nums[right] > 0 + 0 + 0 = 0
#
# Поэтому **дальше искать бессмысленно** — можно сразу прервать цикл через `break`.


class Solution:
    def threeSum(self, nums: list[int]) -> list[list[int]]:
        # Сортируем массив для использования метода двух указателей
        # и удобного пропуска дубликатов
        nums.sort()
        res = []
        n = len(nums)

        # Фиксируем первый элемент тройки
        for i in range(n - 2):
            # Оптимизация: если текущий элемент больше 0, то сумма трех элементов
            # точно не может быть равна 0 (так как массив отсортирован)
            if nums[i] > 0:
                break

            # Пропускаем дубликаты для первого элемента, чтобы избежать повторяющихся троек
            if i > 0 and nums[i] == nums[i - 1]:
                continue

            # Устанавливаем два указателя для поиска оставшейся пары
            left = i + 1
            right = n - 1

            while left < right:
                current_sum = nums[i] + nums[left] + nums[right]

                if current_sum < 0:
                    # Сумма слишком мала, увеличиваем её сдвигом левого указателя
                    left += 1
                elif current_sum > 0:
                    # Сумма слишком велика, уменьшаем её сдвигом правого указателя
                    right -= 1
                else:
                    # Нашли подходящую тройку
                    res.append([nums[i], nums[left], nums[right]])

                    # Пропускаем дубликаты для второго элемента (левый указатель)
                    while left < right and nums[left] == nums[left + 1]:
                        left += 1
                    # Пропускаем дубликаты для третьего элемента (правый указатель)
                    while left < right and nums[right] == nums[right - 1]:
                        right -= 1

                    # Сдвигаем оба указателя, чтобы искать следующие уникальные пары
                    left += 1
                    right -= 1

        return res
