from collections import Counter


class Solution:
    def firstUniqChar(self, s: str) -> int:
        """
        Возвращает индекс первого неповторяющегося символа в строке.
        Если такого символа нет, возвращает -1.

        Алгоритм:
        1. Первый проход: считаем частоту каждого символа
        2. Второй проход: ищем первый символ с частотой 1
        """
        # Считаем частоты всех символов в строке.
        # Counter создаёт словарь вида {'символ': количество_вхождений}.
        # Например, для "leetcode": Counter({'e': 3, 'l': 1, 't': 1, 'c': 1, 'o': 1, 'd': 1})
        #
        # Counter работает за O(N) времени и O(1) памяти
        # (так как алфавит ограничен 26 буквами).
        freq = Counter(s)

        # Второй проход: идём по строке слева направо и ищем
        # первый символ, частота которого равна 1.
        # Возвращаем его индекс — это и есть ответ.
        for i, char in enumerate(s):
            if freq[char] == 1:
                return i

        # Если цикл завершился и мы не нашли уникальный символ,
        # значит все символы повторяются. Возвращаем -1.
        return -1
