class Solution:
    def firstUniqChar(self, s: str) -> int:
        """
        Возвращает индекс первого неповторяющегося символа в строке.
        Если такого символа нет, возвращает -1.

        Алгоритм: два прохода по строке.
        1-й проход: считаем частоту каждого символа.
        2-й проход: ищем первый символ с частотой 1.
        """
        # Словарь для хранения частоты каждого символа.
        # Ключ — символ, значение — количество его появлений в строке.
        # В Python 3.7+ dict сохраняет порядок вставки,
        # но нам это не критично — мы всё равно делаем второй проход по строке.
        char_count = {}

        # === ПЕРВЫЙ ПРОХОД: считаем частоты символов ===
        for char in s:
            # Если символ уже есть в словаре, увеличиваем счётчик на 1.
            # Если нет — добавляем его со значением 1.
            # Метод get(key, default) возвращает значение по ключу,
            # или default (0), если ключа нет в словаре.
            char_count[char] = char_count.get(char, 0) + 1

        # === ВТОРОЙ ПРОХОД: ищем первый символ с частотой 1 ===
        # Проходим по строке с индексами, чтобы вернуть именно индекс,
        # а не сам символ.
        for i, char in enumerate(s):
            # Если частота символа равна 1 — это первый уникальный символ.
            # Возвращаем его индекс.
            if char_count[char] == 1:
                return i

        # Если дошли до конца и не нашли уникальный символ — возвращаем -1
        return -1
