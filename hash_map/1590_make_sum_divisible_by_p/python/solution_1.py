class Solution:
    def minSubarray(self, nums: list[int], p: int) -> int:
        # Находим остаток от деления общей суммы массива на p.
        # Это целевой остаток, который должен иметь удаляемый подмассив.
        target = sum(nums) % p

        # Если общая сумма уже делится на p без остатка,
        # удалять ничего не нужно (длина удаляемого подмассива равна 0).
        if target == 0:
            return 0

        # Словарь для хранения последнего индекса, на котором встречался определенный остаток префиксной суммы.
        # Инициализируем {0: -1}, чтобы корректно обрабатывать случаи,
        # когда удаляемый подмассив начинается с самого первого элемента (индекс 0).
        last_seen = {0: -1}
        curr_mod = 0
        min_len = len(nums)

        for i, num in enumerate(nums):
            # Вычисляем текущий остаток префиксной суммы
            curr_mod = (curr_mod + num) % p

            # Нам нужно найти такой предыдущий остаток (need), чтобы разница давала target по модулю p.
            # (curr_mod - need) % p == target  =>  need = (curr_mod - target) % p
            need = (curr_mod - target) % p

            # Если такой остаток уже встречался ранее, вычисляем длину текущего подмассива
            if need in last_seen:
                min_len = min(min_len, i - last_seen[need])

            # Сохраняем (или обновляем) текущий остаток и его индекс в словаре
            last_seen[curr_mod] = i

        # Если минимальная длина равна длине всего массива, значит,
        # для выполнения условия пришлось бы удалить весь массив,
        # что запрещено по условию задачи. В таком случае возвращаем -1.
        return min_len if min_len < len(nums) else -1
