class Solution:
    def numIdenticalPairs(self, nums: list[int]) -> int:
        """
        Подсчёт пар "на лету": при встрече числа добавляем количество
        его предыдущих вхождений к ответу.
        """
        # Словарь для хранения количества вхождений каждого числа
        count = {}

        total_pairs = 0

        for num in nums:
            # Если число уже встречалось, добавляем количество его вхождений к ответу
            # Это потому что текущее число образует пару с каждым предыдущим вхождением
            if num in count:
                total_pairs += count[num]

            # Увеличиваем счётчик вхождений текущего числа
            count[num] = count.get(num, 0) + 1

        return total_pairs
