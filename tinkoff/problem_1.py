"""
Дан массив целых чисел. Разрешается выполнение следующей операции любое количество раз: два соседних элемента меняются между собой знаками.
Выведите максимальную сумму элементов массива, которую можно получить.
maxPossibleSum([-2, 1, 3]) => 4 // -2 и 1 меняются знаками. [2, -1, 3]
"""

"""
Анализ задачи
Операция инвертирует знаки двух соседних элементов одновременно. Через цепочку таких операций можно инвертировать знаки любой пары элементов (не обязательно соседних). Следовательно, суммарно можно инвертировать знаки чётного количества элементов.
Стратегия:

    Если отрицательных чисел чётное количество — делаем все числа положительными → сумма = сумма модулей.
    Если отрицательных чисел нечётное количество — одно число придётся оставить отрицательным; выбираем число с наименьшим модулем, чтобы потери были минимальны.
    Если в массиве есть ноль, нечётность компенсируется им (ноль не влияет на сумму).
"""


def maxPossibleSum(arr):
    """
    Находит максимальную сумму массива,
    если можно любое число раз менять знаки
    у двух соседних элементов одновременно.
    """

    # Считаем количество отрицательных элементов
    neg_count = sum(1 for x in arr if x < 0)

    # Сумма модулей всех элементов — это максимум,
    # которого мы хотели бы достичь
    total_abs = sum(abs(x) for x in arr)

    # Находим минимальный модуль среди всех элементов
    min_abs = min(abs(x) for x in arr)

    # Если есть ноль или количество отрицательных чётное —
    # все элементы можно сделать неотрицательными
    if 0 in arr or neg_count % 2 == 0:
        return total_abs
    else:
        # Нечётное число отрицательных и нет нуля:
        # один элемент обязан остаться отрицательным.
        # Оставляем отрицательным элемент с наименьшим модулем,
        # теряя 2 * min_abs из идеальной суммы
        return total_abs - 2 * min_abs


# --- Проверки ---
print(maxPossibleSum([-2, 1, 3]))  # 4  (пример из условия)
print(maxPossibleSum([-2, -1, 3]))  # 6  (два минуса → чётное → все в плюс)
print(maxPossibleSum([-5, -3, -2, 1]))  # 11 (три минуса, нет нуля → 11 - 2*1 = 9?
#        проверим: abs sum = 11, min=1, 11-2=9)
print(maxPossibleSum([-5, -3, -2, 0]))  # 10 (ноль компенсирует нечётность)
