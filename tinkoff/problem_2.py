# Пример из условия
print("Тест 1:", maxHappiness([[1, 3], [5, 2], [3, 2]]))  # Ожидаем: 4
# Объяснение: приглашаем друзей [1,3] и [3,2]
# 3 < 2*1 = 2? Нет, 3 >= 2, значит не подходят
# На самом деле: 1 и 3: 3 < 2*1? 3 < 2? Нет
# 1 и 5: 5 < 2? Нет
# 3 и 5: 5 < 6? Да! Счастье = 2+2 = 4

# Все друзья могут прийти
print("Тест 2:", maxHappiness([[1, 1], [1, 2], [1, 3]]))  # Ожидаем: 6

# Только один друг может прийти
print("Тест 3:", maxHappiness([[1, 10], [100, 20]]))  # Ожидаем: 20

# Пустой список
print("Тест 4:", maxHappiness([]))  # Ожидаем: 0

# Один друг
print("Тест 5:", maxHappiness([[5, 7]]))  # Ожидаем: 7

# Сложный случай
print("Тест 6:", maxHappiness([[1, 5], [2, 3], [3, 4], [10, 10]]))
# [1,2,3] могут вместе: 3 < 2*1? 3 < 2? Нет
# [2,3] могут: 3 < 4? Да, счастье = 3+4 = 7
# [1] один: 5
# [10] один: 10
# Ответ: 10


# Сложность: O(n²) время, O(n) память
# Проблема: медленнее, чем sliding window O(n log n)
def maxHappiness_dp_v1(friends):
    if not friends:
        return 0

    friends.sort(key=lambda x: x[0])
    n = len(friends)

    # dp[i] = максимальное счастье, если i-й друг - самый "бедный" в группе
    dp = [0] * n

    for i in range(n):
        dp[i] = friends[i][1]  # хотя бы сам друг
        for j in range(i):
            # Проверяем, можно ли добавить i-го друга к группе, где j-й - самый бедный
            if friends[i][0] < 2 * friends[j][0]:
                dp[i] = max(dp[i], dp[j] + friends[i][1])

    return max(dp)
